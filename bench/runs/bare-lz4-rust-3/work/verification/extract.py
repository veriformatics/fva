#!/usr/bin/env python3
"""Extract the decoder from the hash-pinned shipped module via wasm-tools print.
No source-code build is used. Reject unknown instructions; retain structured labels.
"""
import hashlib, pathlib, re, subprocess, sys
root = pathlib.Path(__file__).resolve().parent.parent
artifact = root / 'lz4-flex.wasm'
assert hashlib.sha256(artifact.read_bytes()).hexdigest() == '1f115e3a5ddee865621f406e2abf545854218cb8dc632d759e998553031aa775'
assert len(artifact.read_bytes()) == 7161
wat = subprocess.check_output(['wasm-tools', 'print', str(artifact)], text=True)
assert '(export "lz4_decompress" (func 7))' in wat
assert '(memory (;0;) 32 32)' in wat
body = wat.split('  (func (;7;)')[1].split('  (func (;8;)')[0]
lines = body.splitlines()[2:]
code, blocks = [], []
for raw in lines:
    line = re.sub(r'\(;.*?;\)|;;.*', '', raw).strip()
    if line == ')': continue
    parts = line.split()
    op = parts[0]
    args = parts[1:]
    if op in ('block', 'loop'):
        blocks.append(len(code)); code.append(None)
        code[-1] = (op, 0)
    elif op == 'end':
        i = blocks.pop(); code[i] = (code[i][0], len(code)); code.append(('end',))
    elif op in ('local.get', 'local.set', 'local.tee', 'br', 'br_if', 'call'):
        code.append((op, int(args[0])))
    elif op == 'i32.const': code.append((op, int(args[0]) % 2**32))
    elif '.load' in op or '.store' in op:
        offset = next((int(a[7:]) for a in args if a.startswith('offset=')), 0)
        width = 8 if op.startswith('i64.') else (1 if '8' in op else 2 if '16' in op else 4)
        assert op in ('i32.load', 'i64.load', 'i32.load8_u', 'i32.load16_u', 'i32.store', 'i64.store', 'i32.store8', 'i32.store16')
        code.append(('load' if '.load' in op else 'store', width, offset))
    else:
        assert op in ('return', 'select', 'unreachable', 'memory.copy', 'memory.fill', 'i32.add', 'i32.sub', 'i32.and', 'i32.shr_u', 'i32.eq', 'i32.ne', 'i32.eqz', 'i32.gt_u', 'i32.ge_u', 'i32.lt_u', 'i32.le_u'), op
        code.append((op,))
assert not blocks
names = {'local.get':'get', 'local.set':'set', 'local.tee':'tee', 'br_if':'brIf', 'i32.const':'const', 'return':'ret', 'unreachable':'trap', 'memory.copy':'copy', 'memory.fill':'fill', 'i32.add':'add', 'i32.sub':'sub', 'i32.and':'and', 'i32.shr_u':'shr', 'i32.eq':'eq', 'i32.ne':'ne', 'i32.eqz':'eqz', 'i32.gt_u':'gt', 'i32.ge_u':'ge', 'i32.lt_u':'lt', 'i32.le_u':'le'}
rows=[]
for instr in code:
    op,*args=instr
    if op in ('block','loop'): rows.append(f'  .block {str(op == "loop").lower()} {args[0]}')
    else: rows.append('  .' + names.get(op, op) + ''.join(' '+str(a) for a in args))
def tree(rows):
    if len(rows) == 1: return '.leaf (' + rows[0].strip() + ')'
    mid = len(rows)//2
    return f'.node {mid} (\n{tree(rows[:mid])}) (\n{tree(rows[mid:])})'
out = '-- Generated by verification/extract.py from the hash-pinned artifact.\nimport Proofs.Machine\nnamespace Verification\ndef decoder : Code :=\n' + tree(rows) + '\nend Verification\n'
target=root/'Proofs'/'Decoder.lean'
if '--check' in sys.argv:
    assert target.read_text() == out, 'extracted code changed'
    print(f'PASS: artifact SHA-256, memory/export, and {len(code)} extracted instructions')
else:
    target.write_text(out)
    print(f'Wrote {len(code)} instructions')
