#!/usr/bin/env python3
"""Generate concrete theorem statements; the resulting Rust is checked by Verus."""
from pathlib import Path
import json
import sys
sys.dont_write_bytecode = True
from cases import CASES

ROOT = Path(__file__).resolve().parent

def seq(xs):
    return 'seq![' + ','.join(map(str,xs)) + ']'

def generate():
    code = ['// Generated by generate_cases.py from reviewed cases.py.', 'verus! {']
    for c in CASES:
        name = c['name']
        code += [f'pub open spec fn {name}_input() -> Init {{',
                 f'    test_input({seq(c["input"])},{c["cap"]})', '}']
        if c['pieces'] is not None:
            pieces = []
            for p in c['pieces']:
                pieces.append('Piece { ' + ', '.join(k+': '+ (seq(v) if isinstance(v,list) else str(v)) for k,v in p.items()) + ' }')
            code += [f'pub open spec fn {name}_certificate() -> Seq<Piece> {{',
                     '    seq![' + ',\n        '.join(pieces) + ']', '}']
        code += [f'pub open spec fn {name}_property() -> bool {{',
                 f'    let m = {name}_input();',
                 '    let s = run(m,initial(m),3000);',
                 f'    init_ok(m) && s.safe && returned(s,{c["result"]})']
        if c['expected'] is not None:
            code += [f'    && read_output(m,s,0,{len(c["expected"])}) == {seq(c["expected"])}',
                     f'    && encoding({name}_certificate()) == m.input',
                     f'    && decoded({name}_certificate(),seq![]) == {seq(c["expected"])}',
                     f'    && grammar({name}_certificate(),seq![])',
                     f'    && valid_block({name}_certificate()) == {str(c["end_ok"]).lower()}',
                     f'    && {len(c["expected"])} <= m.cap']
        code += ['}', f'pub proof fn {name}_checked()', f'    ensures {name}_property(),',
                 '{', f'    assert({name}_property()) by(compute);', '}']
    code += ['}', '']
    return '\n'.join(code)

def runtime_wat():
    lines = [';; Generated runtime harness: imports and executes the original artifact.',
             '(module',
             '  (import "decoder" "memory" (memory 32 32))',
             '  (import "decoder" "lz4_decompress" (func $decode (param i32 i32 i32 i32) (result i32)))',
             '  (func $expect (param i32) local.get 0 i32.eqz if unreachable end)',
             '  (func $check_fill (param $p i32) (param $end i32) (param $value i32)',
             '    block loop local.get $p local.get $end i32.ge_u br_if 1',
             '      local.get $p i32.load8_u local.get $value i32.eq call $expect',
             '      local.get $p i32.const 1 i32.add local.set $p br 0 end end)',
             '  (func (export "check") (result i32)']
    for c in CASES:
        lines += ['    ;; '+c['name'],
                  '    i32.const 131072 i32.const 90 i32.const 1966080 memory.fill',
                  f'    i32.const 262144 i32.const 165 i32.const {c["cap"]} memory.fill']
        for i,b in enumerate(c['input']):
            lines += [f'    i32.const {131072+i} i32.const {b} i32.store8']
        lines += [f'    i32.const 131072 i32.const 262144 i32.const {len(c["input"])} i32.const {c["cap"]}',
                  f'    call $decode i32.const {c["result"]} i32.eq call $expect']
        for i,b in enumerate(c['expected'] or []):
            lines += [f'    i32.const {262144+i} i32.load8_u i32.const {b} i32.eq call $expect']
        for i,b in enumerate(c['input']):
            lines += [f'    i32.const {131072+i} i32.load8_u i32.const {b} i32.eq call $expect']
        lines += [f'    i32.const {131072+len(c["input"])} i32.const 262144 i32.const 90 call $check_fill',
                  f'    i32.const {262144+c["cap"]} i32.const 2097152 i32.const 90 call $check_fill']
    lines += [f'    i32.const {len(CASES)}', '  )', ')', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    outputs = {ROOT/'cases.inc.rs': generate(), ROOT/'cases.json': json.dumps(CASES,indent=2)+'\n', ROOT/'runtime.wat': runtime_wat()}
    if sys.argv[1:] == ['--check']:
        for p,s in outputs.items():
            assert p.read_text()==s, f'{p} differs from generated data'
        print('PASS: concrete theorem statements and runtime vectors match cases.py')
    else:
        assert not sys.argv[1:]
        for p,s in outputs.items():
            p.write_text(s)
