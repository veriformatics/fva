#!/usr/bin/env python3
"""Generate kernel-checkable Lean cases and execute exact-binary WAST cases."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
cases = json.loads((ROOT / "verification/cases.json").read_text())
lean = ["-- Generated by verification/cases.py; do not edit.",
        "import Proofs.Checks", "namespace Verification",
        "set_option maxRecDepth 30000", "set_option maxHeartbeats 0"]
for i, c in enumerate(cases):
    inp = list(bytes.fromhex(c["input"]))
    expected = c["expected"]
    output = "none" if expected is None else "some " + str(list(bytes.fromhex(expected)))
    lean += [f'def case{i} : Case := ⟨"{c["name"]}", {c["src"]}, {c["dst"]}, {inp}, {c["cap"]}, {output}, {str(c["valid"]).lower()}⟩',
             f"theorem case{i}_checked : checkCase case{i} = true := by decide +kernel"]
names = [f"case{i}" for i in range(len(cases))]
lemmas = [f"case{i}_checked" for i in range(len(cases))]
lean += ["def checkedCases : List Case := [" + ", ".join(names) + "]",
         "theorem allCases_checked : checkedCases.all checkCase = true := by",
         "  simp only [checkedCases, List.all_cons, List.all_nil, Bool.true_and, " + ", ".join(lemmas) + "]",
         "end Verification", ""]
generated = "\n".join(lean)
target = ROOT / "Proofs/Cases.lean"
if "--check" in sys.argv:
    assert target.read_text() == generated, "Cases.lean does not match fixtures"
    print(f"PASS: {len(cases)} Lean case statements match cases.json")
else:
    target.write_text(generated)

if "--runtime" not in sys.argv:
    sys.exit(0)

raw = (ROOT / "lz4-c.wasm").read_bytes()
wast = ['(module $artifact binary "' + "".join(f"\\{b:02x}" for b in raw) + '")',
        '(register "lz4" $artifact)']
for c in cases:
    inp = bytes.fromhex(c["input"])
    src, dst, cap = c["src"], c["dst"], c["cap"]
    code = ['(module', '(import "lz4" "memory" (memory 32 32))',
            '(import "lz4" "LZ4_decompress_safe" (func $decode (param i32 i32 i32 i32) (result i32)))',
            '(func (export "check") (result i32) (local $r i32)',
            'i32.const 131072 i32.const 165 i32.const 1966080 memory.fill']
    for offset, b in enumerate(inp):
        code.append(f"i32.const {src + offset} i32.const {b} i32.store8")
    code.append(f"i32.const {src} i32.const {dst} i32.const {len(inp)} i32.const {cap} call $decode local.set $r")
    if c["expected"] is None:
        code.append("local.get $r i32.const 0 i32.lt_s")
    else:
        output = bytes.fromhex(c["expected"])
        code.append(f"local.get $r i32.const {len(output)} i32.eq")
        for offset, b in enumerate(output):
            code.append(f"i32.const {dst + offset} i32.load8_u i32.const {b} i32.eq i32.and")
    # Check bytes immediately outside dst; full read/write coverage is the Lean trace check.
    for address in (dst - 1, dst + cap):
        if 131072 <= address < 2097152 and not src <= address < src + len(inp):
            code.append(f"i32.const {address} i32.load8_u i32.const 165 i32.eq i32.and")
    code.append('))')
    wast += [";; " + c["name"], "\n".join(code), '(assert_return (invoke "check") (i32.const 1))']
with tempfile.TemporaryDirectory(prefix="lz4-verification-") as tmp:
    path = Path(tmp) / "cases.wast"
    path.write_text("\n".join(wast) + "\n")
    env = dict(os.environ, XDG_CACHE_HOME=tmp)
    subprocess.run(["wasmtime", "wast", str(path)], env=env, check=True)
print(f"PASS: {len(cases)} exact-binary Wasmtime cases (returns, output, adjacent canaries)")
