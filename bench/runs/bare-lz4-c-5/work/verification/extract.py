#!/usr/bin/env python3
"""Fail-closed extraction of the decoder's reachable scalar Wasm subset.

The extractor and wasm-tools are trusted for the artifact/model connection.
--check compares freshly extracted text, including the entire artifact hex,
with the committed Lean source. No C compilation is involved.
"""
import hashlib
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
ARTIFACT = ROOT / "lz4-c.wasm"
EXPECTED = "8b73efb63f0467d9999d867007969b75826140dce9e5677bd0439dc6af384ac6"
raw = ARTIFACT.read_bytes()
assert len(raw) == 8469 and hashlib.sha256(raw).hexdigest() == EXPECTED
subprocess.run(["wasm-tools", "validate", str(ARTIFACT)], check=True)
wat = subprocess.check_output(["wasm-tools", "print", str(ARTIFACT)], text=True)
assert '(memory (;0;) 32 32)' in wat
assert '(export "LZ4_decompress_safe" (func 2))' in wat
assert '(import ' not in wat and '(start ' not in wat

binary = {
    "add": "add", "sub": "sub", "and": "band", "xor": "bxor",
    "shl": "shl", "shr_u": "shr", "eq": "eq", "ne": "ne",
    "lt_u": "ltU", "le_u": "leU", "gt_u": "gtU", "ge_u": "geU",
    "lt_s": "ltS", "gt_s": "gtS",
}

def body(lines):
    out = []
    while lines:
        line = lines.pop(0)
        parts = line.split()
        op = parts[0]
        if op == "end":
            return out
        if op in ("block", "loop"):
            assert len(parts) == 1  # no block parameters or results
            nested = body(lines)
            out.append(f".{op} [\n" + ",\n".join("  " + x.replace("\n", "\n  ") for x in nested) + "\n]")
        elif op == "i32.const":
            out.append(f".const {int(parts[1]) % 2**32}")
        elif op.startswith("local."):
            assert op[6:] in ("get", "set", "tee") and len(parts) == 2
            out.append(f".{op[6:]} {int(parts[1])}")
        elif op in ("br", "br_if", "call"):
            assert len(parts) == 2
            n = int(parts[1])
            if op == "call":
                assert n in (3, 4)  # only these helpers are reachable
            out.append(f".{ {'br_if': 'brIf'}.get(op, op)} {n}")
        elif op == "i32.eqz":
            out.append(".unary .eqz")
        elif op.startswith("i32.") and op[4:] in binary:
            out.append(".bin ." + binary[op[4:]])
        elif op in ("i32.load", "i32.load8_u", "i32.load16_u", "i32.store", "i32.store8"):
            width = {"i32.load": 4, "i32.load8_u": 1, "i32.load16_u": 2,
                     "i32.store": 4, "i32.store8": 1}[op]
            offset = 0
            for arg in parts[1:]:
                key, value = arg.split("=")
                assert key in ("offset", "align")
                if key == "offset":
                    offset = int(value)
            out.append(f".{ 'load' if 'load' in op else 'store'} {width} {offset}")
        elif op in ("drop", "select", "return"):
            assert len(parts) == 1
            out.append("." + ("ret" if op == "return" else op))
        else:
            raise ValueError("Unsupported instruction: " + line)
    return out

text = ["-- Generated by verification/extract.py; do not edit.", "import Proofs.Wasm",
        "namespace Verification", f'def artifactSHA256 : String := "{EXPECTED}"',
        f'def artifactHex : String := "{raw.hex()}"']
for index, params, local_count in ((2, 4, 15), (3, 3, 4), (4, 3, 4)):
    section = re.search(rf"^  \(func \(;{index};\).*?(?=^  \(func |^  \(data )", wat, re.M | re.S).group()
    lines = section.splitlines()
    assert lines[0].count("(result i32)") == 1
    assert lines[1].count("i32") == local_count
    assert lines[-1].strip() == ")"
    clean = []
    for line in lines[2:-1]:
        line = re.sub(r"\(;.*?;\)", "", line).split(";;")[0].strip()
        if line:
            clean.append(line)
    instructions = body(clean)
    assert not clean
    text.append(f"def func{index} : Func := ⟨{params}, {local_count}, [\n" +
                ",\n".join("  " + x.replace("\n", "\n  ") for x in instructions) + "\n]⟩")

data_lines = [line.strip() for line in wat.splitlines() if line.strip().startswith("(data ")]
assert len(data_lines) == 1
data_hex = re.fullmatch(r'\(data \(;0;\) \(i32.const 65536\) "((?:\\[0-9a-f]{2})+)"\)', data_lines[0]).group(1)
data = bytes.fromhex(data_hex.replace("\\", ""))
text += ["def tableBytes : List Nat := [" + ", ".join(map(str, data)) + "]",
         "def shipped : Nat → Option Func\n  | 2 => some func2\n  | 3 => some func3\n  | 4 => some func4\n  | _ => none",
         "end Verification", ""]
generated = "\n".join(text)
target = ROOT / "Proofs" / "Artifact.lean"
if "--check" in sys.argv:
    assert target.read_text() == generated, "Artifact.lean does not match extraction"
    print("PASS: exact 8469-byte artifact, validation, decoder/helpers/data extraction")
else:
    target.write_text(generated)
    print("Wrote Proofs/Artifact.lean")
