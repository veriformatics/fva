#!/usr/bin/env python3
"""Shared explicit finite corpus; no claims of exhaustive input coverage."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent.parent
CASES = [
    ("empty_zero", [0], 0, [], True),
    ("empty_one", [0], 1, [], True),
    ("one_literal", [16, 65], 1, [65], True),
    ("one_literal_spare", [16, 65], 64, [65], True),
    ("fourteen_literals", [224] + list(range(14)), 14, list(range(14)), True),
    ("fifteen_literals", [240, 0] + list(range(15)), 15, list(range(15)), True),
    ("overlap_one", [20, 65, 1, 0, 80, 66, 67, 68, 69, 70], 14,
     [65] * 9 + [66, 67, 68, 69, 70], True),
    ("shortcut_eight", [128] + list(range(8)) + [8, 0, 128] + list(range(20, 28)), 64,
     list(range(8)) + list(range(4)) + list(range(20, 28)), True),
    ("zero_offset", [4, 0, 0, 80, 1, 2, 3, 4, 5], 32,
     [0] * 8 + [1, 2, 3, 4, 5], False),
    ("empty_source", [], 1, None, False),
    ("truncated_literal", [16], 16, None, False),
    ("missing_extension", [240], 32, None, False),
    ("too_small", [32, 65, 66], 1, None, False),
    ("offset_before_start", [0, 1, 0, 80, 1, 2, 3, 4, 5], 32, None, False),
    ("zero_cap_nonzero", [1], 0, None, False),
    ("zero_cap_two_bytes", [0, 0], 0, None, False),
]


def lean():
    lines = ["-- Generated by verification/cases.py; finite cases only.",
             "import Proofs.Checks", "namespace Verification", "set_option maxRecDepth 100000",
             "set_option maxHeartbeats 0", "set_option smartUnfolding false"]
    for name, inp, cap, out, strict in CASES:
        expected = "none" if out is None else f"some {out}"
        lines += [f"def {name} : Case := ⟨{inp}, {cap}, {expected}, {str(strict).lower()}, 131072, 196608⟩",
                  f"theorem {name}_checked : check {name} = true := by decide +kernel",
                  f'#eval IO.println "PASS Lean: {name}"']
    lines += ["def cases : List Case := [" + ", ".join(c[0] for c in CASES) + "]",
              "theorem all_cases_checked : ∀ c ∈ cases, check c = true := by",
              "  intro c hc", "  simp only [cases, List.mem_cons, List.not_mem_nil, or_false] at hc",
              "  rcases hc with " + " | ".join("h" for _ in CASES)]
    for name, *_ in CASES:
        lines += [f"  · subst c; exact {name}_checked"]
    lines += ["end Verification", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    target = ROOT / "Proofs" / "Cases.lean"
    if args.check:
        assert target.read_text() == lean()
        print(f"PASS: {len(CASES)} explicit cases match Lean input data")
    else:
        target.write_text(lean())
        print(f"Generated {len(CASES)} cases")
