"""Untrusted certificate generator. Lean checks selection, all bounds and conclusions."""
from collections import Counter
from decimal import Decimal, localcontext
from fractions import Fraction as Q
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent

def rat(q):
    q = Q(q)
    return str(q.numerator) if q.denominator == 1 else f'({q.numerator}/{q.denominator})'

def generate():
    rows = [list(map(int, s.split('\t'))) for s in (ROOT/'counts.tsv').read_text().splitlines()]
    assert len(rows) == 454 and all(len(r) == 7 and min(r) >= 0 for r in rows)
    libs = list(map(sum, zip(*rows)))
    forms = []
    for j in range(7):
        if j == 3:
            forms.append([])
            continue
        xs = [r for r in rows if r[j] > 0 and r[3] > 0]
        n = len(xs)
        ms = [Q(r[j], r[3]) for r in xs]
        aa = [r[j]*r[3] for r in xs]
        def ranks(keys):
            freq = Counter(keys)
            out, less = {}, 0
            for k in sorted(freq):
                out[k] = 2*less + freq[k] + 1
                less += freq[k]
            return out
        mr, ar = ranks(ms), ranks(aa)
        ml, al = n*3//10+1, n//20+1
        kept = [r for r,m,a in zip(xs,ms,aa)
                if 2*ml <= mr[m] <= 2*(n+1-ml) and 2*al <= ar[a] <= 2*(n+1-al)]
        vs = [Q(libs[j]-r[j], libs[j]*r[j]) + Q(libs[3]-r[3], libs[3]*r[3]) for r in kept]
        total = sum(1/v for v in vs)
        forms.append([(1/v/total, Q(r[j]*libs[3], r[3]*libs[j])) for r,v in zip(kept,vs)])
    qs = sorted(set(q for form in forms for w,q in form))
    # Endpoints used for real factor enclosures; these are proposed, never trusted.
    lows = [Q(s) for s in ['.97552','1.28107','1.14774','.95640','.81577','.93242','.95827']]
    highs= [Q(s) for s in ['.97554','1.28110','1.14777','.95643','.81580','.93246','.95830']]
    qs = sorted(set(qs+lows+highs))
    out = ['-- Generated by verification/generate.py; every certificate is checked by Lean.',
           'import Proofs.Model', '', 'namespace Verification', 'set_option maxRecDepth 100000',
           'set_option maxHeartbeats 0', '']
    indices = {}
    with localcontext() as ctx:
        ctx.prec = 60
        for i,q in enumerate(qs):
            indices[q]=i
            u,k=q,0
            while u>1: u/=2; k+=1
            while u<Q(1,2): u*=2; k-=1
            rounded=Q(int((Decimal(q.numerator)/Decimal(q.denominator)).ln()*10**8),10**8)
            out.append(f'def c{i} : LogCertificate := ⟨{rat(q)}, {rat(u)}, {k}, {rat(rounded)}⟩')
    out += ['', 'def forms : List Form := [']
    for f in forms:
        out.append('  ['+',\n   '.join(f'({rat(w)}, c{indices[q]})' for w,q in f)+'],')
    out[-1]=out[-1].rstrip(',')
    out += [']', '', 'def lows : List ℚ := ['+', '.join(map(rat,lows))+']',
            'def highs : List ℚ := ['+', '.join(map(rat,highs))+']',
            'def lowerCerts : List LogCertificate := ['+', '.join(f'c{indices[q]}' for q in lows)+']',
            'def upperCerts : List LogCertificate := ['+', '.join(f'c{indices[q]}' for q in highs)+']',
            '', 'end Verification', '']
    return '\n'.join(out)

if __name__ == '__main__':
    target=ROOT/'Proofs/Certificates.lean'
    result=generate()
    if '--check' in sys.argv:
        assert target.read_text()==result, 'certificate regeneration differs'
        print('Certificate regeneration: PASS')
    else:
        target.write_text(result)
        print(f'Wrote {target.relative_to(ROOT)} ({len(result)} bytes)')
