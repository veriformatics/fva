#!/usr/bin/env python3
"""Lossless, deterministic transfer from shipped decimal/TSV bytes to Lean data."""
import json
from pathlib import Path
from fractions import Fraction

root = Path(__file__).resolve().parent.parent
paths = ['counts.tsv', 'edger-factors.txt', 'rnanorm-factors.txt']
raw = [root.joinpath(p).read_bytes() for p in paths]
assert all(b.endswith(b'\n') and b'\r' not in b for b in raw)
rows = [[int(v) for v in line.split(b'\t')] for line in raw[0].splitlines()]
assert len(rows) == 454 and all(len(r) == 7 and min(r) >= 0 for r in rows)
assert raw[0] == ''.join('\t'.join(map(str,r))+'\n' for r in rows).encode()
out = '-- Generated by verification/embed.py; compared with the shipped bytes on every check.\nimport Mathlib.Data.Rat.Defs\nnamespace Artifact\ndef counts : List (List Nat) := [\n'
out += ',\n'.join('  ['+', '.join(map(str,r))+']' for r in rows) + '\n]\n'
for name, data in zip(['edge', 'rna'], raw[1:]):
    lines = data.decode('ascii').splitlines()
    assert len(lines) == 7
    vals = [Fraction(v) for v in lines]
    out += f'def {name} : List ℚ := [' + ', '.join(f'({v.numerator} / {v.denominator})' for v in vals) + ']\n'
    out += f'def {name}Bytes : String := ' + json.dumps(data.decode('ascii')) + '\n'
out += 'end Artifact\n'
root.joinpath('Proofs/Artifact.lean').write_text(out)
print('Embedded exact 454 × 7 counts and both seven-line decimal artifacts')
