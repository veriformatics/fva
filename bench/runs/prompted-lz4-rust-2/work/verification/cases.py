#!/usr/bin/env python3
"""Concrete witnesses, deliberately separate from both Wasm and format semantics."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
cases = []
def add(name, data, cap, expected, valid, src=131072, dst=1048576):
    cases.append(dict(name=name, input=data, cap=cap, expected=expected,
                      valid=valid, src=src, dst=dst))
def length(n):
    return [255] * (n // 255) + [n % 255]
def literals(data):
    n = len(data)
    return [min(n, 15)*16] + (length(n-15) if n >= 15 else []) + data
def sequence(lit, offset, match):
    return [16*min(len(lit),15)+min(match-4,15)] + \
        (length(len(lit)-15) if len(lit)>=15 else []) + lit + \
        [offset%256,offset//256] + (length(match-19) if match>=19 else [])
def matched(name, lit, offset, count, tail, cap=None, **kwargs):
    out = lit.copy()
    for _ in range(count):
        out.append(out[-offset])
    out += tail
    data = sequence(lit,offset,count) + literals(tail)
    add(name, data, len(out) if cap is None else cap, out, True, **kwargs)
add('empty-input', [], 64, None, False)
add('empty-content', [0], 0, [], True)
add('ignored-final-match-nibble', [15], 0, [], True)
for n in [1,2,3,4,7,8,14,15,16,17,32,33,48,280]:
    content = [i%251 for i in range(n)]
    add(f'literals-{n}', literals(content), n, content, True)
matched('hot-overlap-1', [65], 1, 4, list(range(16)), 64)
matched('hot-wild-18', list(range(14)), 14, 7, list(range(5)), 64)
matched('hot-offset-4', list(range(4)), 4, 4, list(range(16)), 64)
matched('overlap-2', [65,66], 2, 18, list(range(5)))
matched('copy-8', list(range(8)), 8, 8, list(range(5)))
matched('wild-32', list(range(32)), 32, 32, list(range(5)))
matched('wild-64', list(range(64)), 64, 64, list(range(5)))
matched('extended-match-fill', [65], 1, 300, list(range(5)))
matched('extended-match-overlap', [65,66,67], 3, 40, list(range(5)))
add('relaxed-end-conditions', [16,65,1,0,0], 5, [65]*5, False)
add('zero-offset-cold', [16,65,0,0,0], 64, None, False)
add('zero-offset-hot', sequence([65],0,4)+literals(list(range(16))), 64, None, False)
add('offset-before-start', [0,1,0,0], 64, None, False)
add('missing-literals', [32,65], 64, None, False)
add('missing-literal-extension', [240,255], 64, None, False)
add('missing-offset-byte', [16,65,1], 64, None, False)
add('missing-match-extension', [31,65,1,0], 64, None, False)
add('literal-output-too-small', literals(list(range(5))), 4, None, True)
c = cases[17]
add('match-output-too-small', c['input'], 20, None, True)
content = list(range(33))
data = literals(content)
add('source-at-memory-end', data, 33, content, True, src=2097152-len(data), dst=131072)
matched('destination-at-memory-end', [65], 1, 4, list(range(16)), 64, dst=2097152-64)
(root/'verification/cases.json').write_text(json.dumps(cases, indent=2)+'\n')
def lean(c):
    expected = 'none' if c['expected'] is None else '(some '+str(c['expected'])+')'
    return f'  ⟨{json.dumps(c["name"])}, {c["input"]}, {c["cap"]}, {expected}, {str(c["valid"]).lower()}, {c["src"]}, {c["dst"]}⟩'
folder = root/'Proofs/Concrete'
folder.mkdir(exist_ok=True)
for i,c in enumerate(cases):
    lines = ['-- Generated by verification/cases.py; claims are recomputed by the kernels.',
             'import Proofs.Results', 'namespace Verification',
             'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0',
             'set_option cbv.maxSteps 1000000',
             f'def case{i} : Case :=\n'+lean(c),
             f'theorem checked{i} : checkCase case{i} = true := by '+('decide_cbv' if i in (16,20,24,25) else 'rfl'),
             'end Verification', '']
    (folder/f'Case{i}.lean').write_text('\n'.join(lines))
lines = [f'import Proofs.Concrete.Case{i}' for i in range(len(cases))]
(root/'Proofs/Cases.lean').write_text('\n'.join(lines)+'\n')
print(f'Generated {len(cases)} concrete execution statements')
