#!/usr/bin/env python3
"""Extract function 7 from the hash-pinned artifact; emit raw bytes and a checked lift."""
import hashlib
from pathlib import Path

artifact = Path('lz4-flex.wasm').read_bytes()
assert len(artifact) == 7161
assert hashlib.sha256(artifact).hexdigest() == '1f115e3a5ddee865621f406e2abf545854218cb8dc632d759e998553031aa775'
assert artifact[:8] == b'\0asm\x01\0\0\0'

def leb(data, pos, signed=0):
    val, shift = 0, 0
    while True:
        byte = data[pos]; pos += 1
        val |= (byte & 127) << shift; shift += 7
        if byte < 128:
            if signed and byte & 64: val -= 1 << shift
            return val % (1 << signed) if signed else val, pos

sections, p = {}, 8
while p < len(artifact):
    tag = artifact[p]; length, p = leb(artifact, p + 1)
    assert tag not in sections
    sections[tag] = artifact[p:p+length]; p += length
assert p == len(artifact) and 2 not in sections and 8 not in sections
assert sections[5] == bytes([1, 1, 32, 32])  # fixed 32 pages
assert sections[7] == bytes.fromhex('03066d656d6f727902000c6c7a345f636f6d707265737300060e6c7a345f6465636f6d70726573730007')
# No imported functions: function and code indices coincide.
count, p = leb(sections[10], 0)
bodies = []
for _ in range(count):
    length, p = leb(sections[10], p)
    bodies.append(sections[10][p:p+length]); p += length
assert count == 9 and p == len(sections[10])
body = bodies[7]
assert body[:5] == bytes([2, 17, 127, 7, 126])  # 17 i32 and 7 i64 locals
raw = body[5:]
code, p = [], 0
while p < len(raw):
    op = raw[p]; p += 1
    arg = off = 0
    if op in (2, 3):
        arg = raw[p]; p += 1; assert arg == 64
    elif op in (12, 13, 16, 32, 33, 34): arg, p = leb(raw, p)
    elif op in (40, 41, 45, 47, 54, 55, 58, 59):
        arg, p = leb(raw, p); off, p = leb(raw, p)
    elif op in (65, 66): arg, p = leb(raw, p, 32 if op == 65 else 64)
    elif op == 252:
        arg, p = leb(raw, p)
        assert arg in (10, 11)
        assert raw[p] == 0; p += 1
        if arg == 10: assert raw[p] == 0; p += 1
    else: assert op in (0, 11, 15, 27, 69, 70, 71, 73, 75, 77, 79, 106, 107, 113, 114, 118), hex(op)
    code.append((op, arg, off))
ends, stack = [0]*len(code), []
for i, (op, _, _) in enumerate(code):
    if op in (2, 3): stack.append(i)
    elif op == 11 and stack: ends[stack.pop()] = i
assert not stack and code[-1][0] == 11
data = sections[11]
segments, q = leb(data, 0)
assert segments == 1 and data[q:q+2] == bytes([0, 65])
base, q = leb(data, q+2, 32)
assert base == 65536 and data[q] == 11
size, q = leb(data, q+1)
initial_data = data[q:q+size]
assert q+size == len(data)
out = ['-- Generated by verification/lift.py; do not edit.', 'import Proofs.Machine', 'namespace Artifact',
       'def raw : List Nat := [' + ','.join(map(str, raw)) + ']',
       'def initialData : Memory := putBytes [] 65536 [' + ','.join(map(str, initial_data)) + ']',
       'def code : Array Insn := #[']
out += ['  ⟨%d,%d,%d⟩,' % ins for ins in code]
out += [']', 'def ends : Array Nat := #[' + ','.join(map(str, ends)) + ']',
        'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0',
        'theorem lift_exact : decode raw.length raw = some code.toList := by rfl',
        'theorem ends_exact : checkEnds code ends = true := by decide', 'end Artifact', '']
Path('Proofs/Artifact.lean').write_text('\n'.join(out))
print(f'Pinned artifact: {len(artifact)} bytes; function 7: {len(body)} bytes, {len(code)} instructions')
