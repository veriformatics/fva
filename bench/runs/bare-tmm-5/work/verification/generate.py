"""Generate proof data. No generated numerical claim is accepted without checking.
Run from the project root. Uses Decimal only to propose bounds, not to prove them.
"""
from pathlib import Path
from decimal import Decimal, localcontext, ROUND_FLOOR
from fractions import Fraction as F
import json
import sys
sys.path.insert(0, str(Path('verification').resolve()))
from replay import replay

S = 10**18

def rat(q):
    q = F(q)
    return f'({q.numerator} / {q.denominator} : ℚ)'

def box(lo, hi):
    return f'⟨{rat(lo)}, {rat(hi)}⟩'

def logbox(q, pad=20):
    q = F(q)
    with localcontext() as ctx:
        ctx.prec = 100
        v = (Decimal(q.numerator)/Decimal(q.denominator)).ln()
        n = int((v*S).to_integral_value(rounding=ROUND_FLOOR))
        return F(n-pad,S), F(n+1+pad,S)

x = [list(map(int,l.split())) for l in Path('counts.tsv').read_text().splitlines()]
libs = [sum(row[j] for row in x) for j in range(7)]
keys = sorted(set(v for row in x for v in row if v) | set(libs))
lo2, hi2 = logbox(2, pad=0)
lines = ['-- Generated by verification/generate.py; all certificates checked by the kernel.',
         'import Proofs.Intervals', 'set_option maxRecDepth 100000',
         'set_option maxHeartbeats 0', 'namespace TMM',
         f'def logTwoBox : Box := {box(lo2,hi2)}',
         'theorem logTwo_sound : logTwoBox.Holds (Real.log 2) := by',
         '  have h := log_series_bound (1/3) 24 (by norm_num) (by norm_num)',
         '  norm_num at h',
         '  exact widen_sound h (by decide +kernel) (by decide +kernel)',
         f'def logKeys : List ℕ := {keys}', 'def logBox (n : ℕ) : Box :=', '  match n with']
for n in keys:
    lines.append(f'  | {n} => {box(*logbox(n))}')
lines.append('  | _ => ⟨0,0⟩')
for n in keys:
    k = n.bit_length()-1
    z = F(n-2**k,n+2**k)
    lines += [f'theorem log_{n}_sound : (logBox {n}).Holds (Real.log {n}) := by',
              f'  have h := log_bound {rat(n)} {rat(z)} {k} 24 logTwoBox (logBox {n}) logTwo_sound',
              '    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)',
              '  simpa using h']
lines += ['theorem logBox_sound {n : ℕ} (h : n ∈ logKeys) :',
          '    (logBox n).Holds (Real.log n) := by',
          '  simp only [logKeys, List.mem_cons, List.not_mem_nil, or_false] at h',
          '  rcases h with '+' | '.join('rfl' for n in keys)]
lines += [f'  · simpa using log_{n}_sound' for n in keys]
lines += ['end TMM']
Path('Proofs/Logs.lean').write_text('\n'.join(lines)+'\n')

_, nmasks = replay()
emasks = [list(map(int,l.split(','))) for l in Path('verification/edger-masks.csv').read_text().splitlines()]

def idealmask(j):
    inds = [k for k,row in enumerate(x) if row[j]*row[3]]
    ms = [F(x[k][j],x[k][3]) for k in inds]
    aa = [x[k][j]*x[k][3] for k in inds]
    def rank(v):
        return [2*sum(w<t for w in v)+sum(w==t for w in v)+1 for t in v]
    rm, ra = rank(ms),rank(aa)
    n = len(inds)
    return [k for k,m,a in zip(inds,rm,ra) if
            2*(n*3//10+1)<=m<=2*(n-n*3//10) and 2*(n//20+1)<=a<=2*(n-n//20)]
imasks = [idealmask(j) for j in range(7)]
Path('verification/masks.json').write_text(json.dumps(dict(ideal=imasks,edgeR=emasks,RNAnorm=nmasks),indent=2)+'\n')
lines = ['-- Generated; contains exact input literals and discrete trimming witnesses.',
         'import Proofs.Intervals', 'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0', 'namespace TMM',
         'def countsText : String := include_str "../counts.tsv"',
         'def edgeText : String := include_str "../edger-factors.txt"',
         'def rnaText : String := include_str "../rnanorm-factors.txt"',
         'def counts : List (List ℕ) := '+str(x),
         'def renderCounts : String := String.intercalate "\\n" (counts.map fun r => String.intercalate "\\t" (r.map toString)) ++ "\\n"',
         'theorem counts_bytes : renderCounts = countsText := by native_decide',
         f'def libs : List ℕ := {libs}',
         'theorem library_sizes : libs = (List.range 7).map (fun i => (counts.map fun r => r[i]!).sum) := by native_decide',
         'theorem matrix_shape : counts.length = 454 ∧ (∀ r ∈ counts, r.length = 7) ∧ (∀ r ∈ counts, ∃ n ∈ r, 0 < n) := by native_decide']
for label,file in [('edge','edger-factors.txt'),('rna','rnanorm-factors.txt')]:
    text = Path(file).read_text()
    lines += [f'theorem {label}_bytes : {label}Text = {json.dumps(text)} := by decide +kernel',
              f'def {label}Factors : List ℚ := ['+', '.join(rat(F(t)) for t in text.splitlines())+']']
lines += ['def parseDecimal (s : String) : ℚ :=',
          '  let parts := s.splitOn "."',
          '  (parts[0]!.toNat! : ℚ) + (parts[1]!.toNat! : ℚ)/(10^parts[1]!.length : ℚ)',
          'def parseFactors (s : String) : List ℚ :=',
          '  ((s.splitOn "\\n").filter (· != "")).map parseDecimal',
          'theorem edge_decimals : edgeFactors = parseFactors edgeText := by native_decide',
          'theorem rna_decimals : rnaFactors = parseFactors rnaText := by native_decide']
for label,mask in [('ideal',imasks),('edge',emasks),('rna',nmasks)] :
    lines.append(f'def {label}Masks : List (List ℕ) := {mask}')
lines += ['end TMM']
Path('Proofs/Data.lean').write_text('\n'.join(lines)+'\n')
print('Generated Logs.lean, Data.lean, masks.json')

# Interval arithmetic here only proposes short summaries; Lean checks inclusion.
def badd(a,b): return a[0]+b[0],a[1]+b[1]
def bsub(a,b): return a[0]-b[1],a[1]-b[0]
def bmul(a,b):
    cs=[x*y for x in a for y in b]
    return min(cs),max(cs)
def bdiv(a,b):
    assert b[0]>0
    return bmul(a,(1/b[1],1/b[0]))
def bsums(xs):
    return sum((a for a,b in xs),F(0)),sum((b for a,b in xs),F(0))
def rawbox(mask,j):
    ns,ds=[],[]
    for k in mask:
        o,r=x[k][j],x[k][3]
        w=1/(F(libs[j]-o,libs[j]*o)+F(libs[3]-r,libs[3]*r))
        low=F((w*S).__floor__(),S)
        wb=(low,low+F(1,S))
        lb=bsub(bsub(logbox(o),logbox(r)),bsub(logbox(libs[j]),logbox(libs[3])))
        ns.append(bmul(wb,lb));ds.append(wb)
    return bdiv(bsums(ns),bsums(ds))

lines=['-- Generated numerical witnesses; interval inclusions and logarithms checked in Lean.',
       'import Proofs.Model','set_option maxRecDepth 100000','set_option maxHeartbeats 0','namespace TMM']
cert_header = lines.copy()
for label,masks in [('ideal',imasks),('edge',emasks),('rna',nmasks)]:
    label_start = len(lines)
    summaries=[]
    for j,mask in enumerate(masks):
        low,high=rawbox(mask,j)
        summaries.append((F((low*10**15).__floor__(),10**15),F((high*10**15).__ceil__(),10**15)))
    lines += [f'def {label}Summary (i : ℕ) : Box :=', '  match i with']
    lines += [f'  | {j} => {box(*b)}' for j,b in enumerate(summaries)]
    lines += ['  | _ => ⟨0,0⟩',
              f'theorem {label}_valid : ∀ i ∈ List.range 7, validPairs (pairsOfMask {label}Masks i) i := by',
              '  decide +kernel',
              f'theorem {label}_summary_contains : ∀ i ∈ List.range 7,',
              f'    ({label}Summary i).lo ≤ (rawBox (pairsOfMask {label}Masks i) i).lo ∧',
              f'    (rawBox (pairsOfMask {label}Masks i) i).hi ≤ ({label}Summary i).hi := by',
              '  decide +kernel',
              f'theorem {label}_summary_sound (i : ℕ) (hi : i ∈ List.range 7) :',
              f'    ({label}Summary i).Holds (raw (pairsOfMask {label}Masks i) i) := by',
              f'  exact widen_sound (rawBox_sound _ _ ({label}_valid i hi))',
              f'    ({label}_summary_contains i hi).1 ({label}_summary_contains i hi).2']
    if label=='ideal':
        # Only 6 decimal places are needed for the diagnostic and coarse tolerance.
        endpoints=[]
        with localcontext() as ctx:
            ctx.prec=100
            raws=[]
            for j,mask in enumerate(masks):
                numer=Decimal(0);denom=Decimal(0)
                for k in mask:
                    o,r=x[k][j],x[k][3]
                    w=1/(F(libs[j]-o,libs[j]*o)+F(libs[3]-r,libs[3]*r))
                    wd=Decimal(w.numerator)/Decimal(w.denominator)
                    numer+=wd*(Decimal(o).ln()-Decimal(r).ln()-Decimal(libs[j]).ln()+Decimal(libs[3]).ln())
                    denom+=wd
                raws.append(numer/denom)
            mean=sum(raws)/7
            for raw_ in raws:
                f=(raw_-mean).exp()
                n=int((f*10**6).to_integral_value(rounding=ROUND_FLOOR))
                endpoints.append((F(n,10**6),F(n+1,10**6)))
    else:
        vals=[F(t) for t in Path(label=='edge' and 'edger-factors.txt' or 'rnanorm-factors.txt').read_text().splitlines()]
        endpoints=[(v-F(1,10**12),v+F(1,10**12)) for v in vals]
    lines += [f'def {label}Endpoints (i : ℕ) : Box :=','  match i with']
    lines += [f'  | {j} => {box(a,b)}' for j,(a,b) in enumerate(endpoints)]
    lines += ['  | _ => ⟨1,1⟩']
    for j,(a,b) in enumerate(endpoints):
        for side,q in [('lo',a),('hi',b)]:
            z=(q-1)/(q+1)
            lb=logbox(q)
            name=f'{label}_{j}_{side}'
            lines += [f'def {name} : Box := {box(*lb)}',
                      f'theorem {name}_sound : {name}.Holds (Real.log ({rat(q)} : ℝ)) := by',
                      f'  exact log_signed_bound {rat(q)} {rat(z)} 24 {name}',
                      '    (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)']
        lines += [f'theorem {label}_{j}_enclosed :',
                  f'    ({label}Endpoints {j}).Holds (factor {label}Masks {j}) := by',
                  f'  exact exp_enclosure (center_summary_sound {label}Masks {label}Summary {label}_summary_sound {j} (by decide))',
                  f'    {label}_{j}_lo_sound {label}_{j}_hi_sound (by decide +kernel) (by decide +kernel)',
                  '    (by decide +kernel) (by decide +kernel)']
    lines += [f'theorem {label}_enclosed (i : ℕ) (hi : i ∈ List.range 7) :',
              f'    ({label}Endpoints i).Holds (factor {label}Masks i) := by',
              '  simp only [List.mem_range] at hi','  interval_cases i']
    lines += [f'  · exact {label}_{j}_enclosed' for j in range(7)]
    Path(f'Proofs/{label.title()}Certificates.lean').write_text('\n'.join(cert_header+lines[label_start:]+['end TMM'])+'\n')
Path('Proofs/Certificates.lean').write_text('import Proofs.IdealCertificates\nimport Proofs.EdgeCertificates\nimport Proofs.RnaCertificates\n')
print('Generated Certificates.lean')
