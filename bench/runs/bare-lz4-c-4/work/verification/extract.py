#!/usr/bin/env python3
"""Decode the shipped Wasm's reachable decoder functions into Lean syntax.

No C compiler or source-code correspondence is used. Unknown instructions,
non-void structured control, imports, and unexpected module metadata fail closed.
"""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXPECTED = '8b73efb63f0467d9999d867007969b75826140dce9e5677bd0439dc6af384ac6'


class Reader:
    def __init__(self, data):
        self.data, self.pos = data, 0

    def byte(self):
        b = self.data[self.pos]
        self.pos += 1
        return b

    def take(self, n):
        assert self.pos + n <= len(self.data)
        b = self.data[self.pos:self.pos+n]
        self.pos += n
        return b

    def leb(self, signed=False):
        value = shift = 0
        while True:
            b = self.byte()
            value |= (b & 127) << shift
            shift += 7
            assert shift <= 35
            if not b & 128:
                break
        if signed and b & 64:
            value -= 1 << shift
        return value

    def name(self):
        return self.take(self.leb()).decode('utf-8')

    def done(self):
        assert self.pos == len(self.data)


PLAIN = {0x0f, 0x1a, 0x1b, 0x45, 0x46, 0x47, 0x48, 0x49,
         0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f,
         0x6a, 0x6b, 0x71, 0x72, 0x73, 0x74, 0x76}
INDEX = {0x0c, 0x0d, 0x10, 0x20, 0x21, 0x22}
MEM = {0x28, 0x2d, 0x2f, 0x36, 0x3a}


def instructions(r):
    result = []
    while True:
        op = r.byte()
        if op == 0x0b:
            return result
        if op in (2, 3):
            assert r.byte() == 0x40, 'only void blocks supported'
            result.append(('block' if op == 2 else 'loop', instructions(r)))
        elif op == 0x41:
            result.append(('op', op, r.leb(True) % (1 << 32), 0))
        elif op in INDEX:
            result.append(('op', op, r.leb(), 0))
        elif op in MEM:
            align, offset = r.leb(), r.leb()
            assert align <= {0x28: 2, 0x2d: 0, 0x2f: 1,
                             0x36: 2, 0x3a: 0}[op]
            result.append(('op', op, offset, 0))
        elif op in PLAIN:
            result.append(('op', op, 0, 0))
        else:
            raise ValueError(f'unsupported opcode {op:#x}')


def emit(code, level=1):
    pad = '  ' * level
    lines = []
    for i in code:
        if i[0] == 'op':
            lines.append(f'{pad}.op {i[1]} {i[2]},')
        else:
            lines.append(f'{pad}.{i[0]} [\n{emit(i[1], level+1)}\n{pad}],')
    return '\n'.join(lines).removesuffix(',')


def main():
    data = (ROOT / 'lz4-c.wasm').read_bytes()
    assert len(data) == 8469 and hashlib.sha256(data).hexdigest() == EXPECTED
    r = Reader(data)
    assert r.take(8) == b'\0asm\x01\0\0\0'
    sections = {}
    while r.pos < len(data):
        tag, n = r.byte(), r.leb()
        assert tag not in sections and tag != 0
        sections[tag] = Reader(r.take(n))
    assert set(sections) == {1, 3, 5, 6, 7, 10, 11}
    t = sections[1]
    types = []
    for _ in range(t.leb()):
        assert t.byte() == 0x60
        params = [t.byte() for _ in range(t.leb())]
        results = [t.byte() for _ in range(t.leb())]
        assert all(p == 0x7f for p in params) and results == [0x7f]
        types.append(len(params))
    t.done()
    f = sections[3]
    ftypes = [f.leb() for _ in range(f.leb())]
    f.done()
    m = sections[5]
    assert [m.leb() for _ in range(4)] == [1, 1, 32, 32]
    m.done()
    e = sections[7]
    exports = {e.name(): (e.byte(), e.leb()) for _ in range(e.leb())}
    e.done()
    assert exports == {'memory': (2, 0), 'LZ4_compress_default': (0, 1),
                       'LZ4_decompress_safe': (0, 2)}
    c = sections[10]
    assert c.leb() == len(ftypes)
    bodies = [c.take(c.leb()) for _ in ftypes]
    c.done()
    generated = ['-- Generated by verification/extract.py from the hash-pinned artifact.',
                 'import Proofs.Wasm', 'namespace Verification']
    for index in (2, 3, 4):
        b = Reader(bodies[index])
        locals_count = 0
        for _ in range(b.leb()):
            n, ty = b.leb(), b.byte()
            assert ty == 0x7f
            locals_count += n
        code = instructions(b)
        b.done()
        if index == 2:
            # Keep the early-exit proof from expanding the main decoding loop.
            assert len(code) == 4 and code[2][0] == 'block'
            prefix, remainder = code[2][1][:8], code[2][1][8:]
            generated += ['def decoderRest : List Instr := [', emit(remainder), ']']
            generated += ['def f2 : Func :=',
                          f'  ⟨4, {locals_count}, [', emit(code[:2], 2) + ',',
                          '    .block ([', emit(prefix, 3),
                          '    ] ++ decoderRest),', emit(code[3:], 2), '  ]⟩']
        else:
            generated += [f'def f{index} : Func :=',
                          f'  ⟨{types[ftypes[index]]}, {locals_count}, [',
                          emit(code, 2), '  ]⟩']
    d = sections[11]
    assert d.leb() == 1 and d.leb() == 0 and d.byte() == 0x41
    assert d.leb(True) == 65536 and d.byte() == 0x0b
    init = d.take(d.leb())
    d.done()
    generated += ['def initialData : List Nat := [' + ', '.join(map(str, init)) + ']',
                  'def decoderModule : Nat → Option Func',
                  '  | 2 => some f2 | 3 => some f3 | 4 => some f4 | _ => none',
                  'end Verification', '']
    output = '\n'.join(generated)
    path = ROOT / 'Proofs/Artifact.lean'
    if '--check' in sys.argv:
        assert path.read_text() == output, 'generated Lean does not match artifact'
        print('PASS: pinned artifact, exports, fixed memory, and extracted functions')
    else:
        path.write_text(output)
        print('Wrote Proofs/Artifact.lean')


if __name__ == '__main__':
    main()
