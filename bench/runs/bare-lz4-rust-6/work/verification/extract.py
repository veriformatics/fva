#!/usr/bin/env python3
"""Strict, deterministic extraction of function 7 from the pinned artifact.
--check compares generated Lean data, instead of changing it.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHA256 = '1f115e3a5ddee865621f406e2abf545854218cb8dc632d759e998553031aa775'


def uleb(data, p):
    value = shift = 0
    for _ in range(5):
        b = data[p]
        p += 1
        value |= (b & 127) << shift
        if b < 128:
            return value, p
        shift += 7
    raise ValueError('oversize ULEB')


def extract():
    data = (ROOT / 'lz4-flex.wasm').read_bytes()
    assert hashlib.sha256(data).hexdigest() == SHA256, 'artifact digest mismatch'
    assert data[:8] == b'\0asm\x01\0\0\0'
    sections = {}
    p = 8
    while p < len(data):
        tag = data[p]
        size, start = uleb(data, p + 1)
        assert tag not in sections and start + size <= len(data)
        sections[tag] = data[start:start + size]
        p = start + size
    assert 2 not in sections and 8 not in sections, 'unexpected imports/start'
    assert sections[5] == bytes([1, 1, 32, 32]), 'memory must be fixed 32 pages'
    assert sections[7] == bytes.fromhex(
        '03066d656d6f727902000c6c7a345f636f6d70726573730006'
        '0e6c7a345f6465636f6d70726573730007'), 'export mismatch'
    code = sections[10]
    count, p = uleb(code, 0)
    assert count == 9
    bodies = []
    for _ in range(count):
        size, p = uleb(code, p)
        bodies.append(code[p:p + size])
        p += size
    assert p == len(code)
    body = bodies[7]
    assert body[:5] == bytes([2, 17, 0x7f, 7, 0x7e])
    raw = body[5:]
    instructions = []
    p = 0
    simple = {0: 'unreachable', 0xb: 'end', 0xf: 'ret', 0x1b: 'select',
              0x45: 'eqz', 0x46: 'eq', 0x47: 'ne', 0x49: 'lt', 0x4b: 'gt',
              0x4d: 'le', 0x4f: 'ge', 0x6a: 'add', 0x6b: 'sub',
              0x71: 'and', 0x76: 'shr'}
    imm = {0xc: 'br', 0xd: 'brIf', 0x10: 'call', 0x20: 'get',
           0x21: 'set', 0x22: 'tee'}
    memory = {0x28: ('load', 4), 0x29: ('load', 8), 0x2d: ('load', 1),
              0x2f: ('load', 2), 0x36: ('store', 4), 0x37: ('store', 8),
              0x3a: ('store', 1), 0x3b: ('store', 2)}
    while p < len(raw):
        op = raw[p]
        p += 1
        if op in simple:
            instr = '.' + simple[op]
        elif op in imm:
            v, p = uleb(raw, p)
            instr = f'.{imm[op]} {v}'
        elif op in (2, 3):
            assert raw[p] == 0x40
            p += 1
            instr = '.block' if op == 2 else '.loop'
        elif op == 0x41:
            start = p
            v, p = uleb(raw, p)
            if raw[p - 1] & 64:
                v -= 1 << (7 * (p - start))
            instr = f'.const {v % (1 << 32)}'
        elif op in memory:
            align, p = uleb(raw, p)
            offset, p = uleb(raw, p)
            name, width = memory[op]
            assert 1 << align <= width
            instr = f'.{name} {width} {offset}'
        elif op == 0xfc:
            sub, p = uleb(raw, p)
            assert sub in (10, 11)
            zeros = 2 if sub == 10 else 1
            assert raw[p:p + zeros] == bytes(zeros)
            p += zeros
            instr = '.copy' if sub == 10 else '.fill'
        else:
            raise ValueError(f'unsupported opcode {op:x}')
        instructions.append(instr)
    def nums(bs):
        return ',\n  '.join(', '.join(map(str, bs[i:i + 24])) for i in range(0, len(bs), 24))
    result = '''-- Generated by verification/extract.py. Do not edit.
import Proofs.Wasm
namespace Verification
set_option maxRecDepth 100000
set_option maxHeartbeats 0
'''
    result += f'def artifact : List Nat := [\n  {nums(data)}\n]\n'
    result += f'def rawBody : List Nat := [\n  {nums(body)}\n]\n'
    result += 'def program : Array Instr := #[\n  ' + ',\n  '.join(instructions) + '\n]\n'
    result += '''
-- This equality connects the embedded body to the entire embedded artifact.
theorem body_bytes : (artifact.drop 4437).take 2000 = rawBody := by decide
theorem local_declarations : rawBody.take 5 = [2, 17, 127, 7, 126] := by decide
-- Independent Lean decoder checks the generated instruction list.
theorem decoded_body : decode 2001 (rawBody.drop 5) = some program.toList := by decide
'''
    result += f'theorem instruction_count : program.size = {len(instructions)} := by decide\n'
    result += 'end Verification\n'
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = extract()
    target = ROOT / 'Proofs/Artifact.lean'
    if args.check:
        assert target.read_text() == result, 'generated data mismatch'
        print('PASS: pinned artifact, module interface, exact generated Lean data')
    else:
        target.write_text(result)
        print('Wrote', target.relative_to(ROOT))
