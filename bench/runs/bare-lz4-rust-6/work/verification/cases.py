#!/usr/bin/env python3
"""Reviewable concrete cases shared by Lean and Wasmtime; never fuzz results.
The --check option checks committed generated Lean data.
"""
import argparse
from pathlib import Path
import subprocess
import tempfile
from extract import ROOT, extract

CASES = []


def case(name, block, cap, expected, fmt=1, src=131072, dst=1048576):
    CASES.append(dict(name=name, block=block, cap=cap, expected=expected,
                      fmt=fmt, src=src, dst=dst))


def literals(xs):
    n = len(xs)
    if n < 15:
        return [16 * n] + xs
    extra = n - 15
    return [240] + [255] * (extra // 255) + [extra % 255] + xs


case('empty-input', [], 64, None, 0)
case('empty-block', [0], 0, [])
case('empty-token-low-nibble', [15], 0, [])
for n in [1, 2, 3, 4, 5, 7, 8, 9, 14, 15, 16, 17, 31, 32, 33]:
    xs = [(i * 37 + n) % 256 for i in range(n)]
    case(f'literals-{n}', literals(xs), n, xs)
xs = list(range(15))
case('literal-cap-too-small', literals(xs), 14, None)
case('missing-literal-extension', [240], 64, None, 0)
case('unterminated-literal-extension', [240, 255], 64, None, 0)
case('truncated-literals', [80, 1, 2, 3, 4], 64, None, 0)
case('truncated-offset', [16, 65, 1], 64, None, 0)
case('zero-offset-slow', [16, 65, 0, 0, 80, 1, 2, 3, 4, 5], 64, None, 0)
case('offset-before-start-slow', [16, 65, 2, 0, 80, 1, 2, 3, 4, 5], 64, None, 0)
case('maximum-offset-before-start', [0, 255, 255, 80, 1, 2, 3, 4, 5], 64, None, 0)
case('missing-match-extension', [31, 65, 1, 0], 64, None, 0)
case('unterminated-match-extension', [31, 65, 1, 0, 255], 64, None, 0)
case('match-cap-too-small', [19, 65, 1, 0, 80, 1, 2, 3, 4, 5], 7, None)
case('overlap-offset-one', [19, 65, 1, 0, 80, 1, 2, 3, 4, 5], 13, [65]*8 + [1, 2, 3, 4, 5])
case('overlap-offset-two', [35, 65, 66, 2, 0, 80, 1, 2, 3, 4, 5], 14,
     [65, 66, 65, 66, 65, 66, 65, 66, 65] + [1, 2, 3, 4, 5])
case('short-disjoint-match', [64, 1, 2, 3, 4, 4, 0, 128] + list(range(8)), 16,
     [1, 2, 3, 4]*2 + list(range(8)))
case('wild-32-match', [64, 1, 2, 3, 4, 4, 0, 128] + list(range(8)), 64,
     [1, 2, 3, 4]*2 + list(range(8)))
xs = list(range(40))
case('wild-64-match', [255, 25] + xs + [40, 0, 14, 128] + list(range(8)), 128,
     xs + xs[:33] + list(range(8)))
xs = list(range(80))
case('bulk-match', [255, 65] + xs + [80, 0, 51, 80] + list(range(5)), 160,
     xs + xs[:70] + list(range(5)))
tail = list(range(20))
case('hot-overlap', [19, 65, 1, 0] + literals(tail), 64, [65]*8 + tail)
case('hot-disjoint', [128] + list(range(8)) + [8, 0] + literals(tail), 64,
     list(range(8)) + list(range(4)) + tail)
case('hot-two-matches', [224] + list(range(14)) + [14, 0, 14, 18, 0] + literals(tail), 128,
     (list(range(14)) + list(range(4)))*2 + tail)
case('zero-offset-hot', [16, 65, 0, 0] + literals(tail), 64, None, 0)
case('offset-before-start-hot', [16, 65, 2, 0] + literals(tail), 64, None, 0)
case('relaxed-end-conditions', [16, 65, 1, 0, 0], 5, [65]*5, 2)
case('missing-final-token', [16, 65, 1, 0], 64, None, 0)
case('source-at-memory-end', literals([1, 2, 3, 4, 5]), 5, [1, 2, 3, 4, 5],
     src=2097152-6, dst=131072)
case('destination-at-memory-end', literals([1, 2, 3, 4, 5]), 5, [1, 2, 3, 4, 5],
     dst=2097152-5)
for n in [270, 525]:
    xs = [i % 256 for i in range(n)]
    case(f'literals-extension-{n}', literals(xs), n, xs)
for extra, match_len in [([255, 0], 274), ([255, 255, 0], 529)]:
    case(f'match-extension-{match_len}', [31, 65, 1, 0] + extra + [80, 1, 2, 3, 4, 5],
         match_len + 6, [65]*(match_len + 1) + [1, 2, 3, 4, 5])


def lean_list(xs):
    return '[' + ', '.join(map(str, xs)) + ']'


def lean_data():
    text = '''-- Generated by verification/cases.py. Do not edit.
import Proofs.Checks
namespace Verification
set_option maxRecDepth 100000
set_option maxHeartbeats 0
'''
    for i, c in enumerate(CASES):
        expected = 'none' if c['expected'] is None else 'some ' + lean_list(c['expected'])
        text += f'''def case{i} : Case := {{
  name := "{c['name']}"
  input := {lean_list(c['block'])}
  cap := {c['cap']}
  expected := {expected}
  format := {c['fmt']}
  src := {c['src']}
  dst := {c['dst']}
}}
theorem checked_{i} : checkCase case{i} = true := by native_decide
'''
    text += 'def allCases : List Case := [' + ', '.join(f'case{i}' for i in range(len(CASES))) + ']\n'
    text += 'theorem cases_checked : allCases.all checkCase = true := by\n  simp [allCases, ' + ', '.join(f'checked_{i}' for i in range(len(CASES))) + ']\n'
    text += 'end Verification\n'
    return text


def escapes(data):
    return ''.join(f'\\{b:02x}' for b in data)


def wast():
    data = (ROOT / 'lz4-flex.wasm').read_bytes()
    text = '(module $decoder binary "' + escapes(data) + '")\n(register "decoder" $decoder)\n'
    # Helper uses a byte reference array in its own data region below caller space.
    text += '''(module $tests
  (import "decoder" "memory" (memory 32 32))
  (import "decoder" "lz4_decompress" (func $decode (param i32 i32 i32 i32) (result i32)))
'''
    for i, c in enumerate(CASES):
        src, dst, cap, block = c['src'], c['dst'], c['cap'], c['block']
        # Passive data does not change the decoder's own static data.
        text += f'  (data $input{i} "{escapes(block)}")\n'
        text += f'  (func (export "case{i}") (result i32) (local $i i32)\n'
        text += '    (memory.fill (i32.const 131072) (i32.const 165) (i32.const 1966080))\n'
        text += f'    (memory.init $input{i} (i32.const {src}) (i32.const 0) (i32.const {len(block)}))\n'
        text += f'    (if (i32.ne (call $decode (i32.const {src}) (i32.const {dst}) (i32.const {len(block)}) (i32.const {cap})) (i32.const {len(c["expected"]) if c["expected"] is not None else -1})) (then unreachable))\n'
        if c['expected'] is not None:
            for j, b in enumerate(c['expected']):
                text += f'    (if (i32.ne (i32.load8_u (i32.const {dst+j})) (i32.const {b})) (then unreachable))\n'
        # Scan every byte in the caller arena outside dst, including the input.
        # Each still equals its pre-call value. Reads by the decoder aren't observed.
        text += '''    (local.set $i (i32.const 131072))
    (loop $scan
'''
        text += f'''      (if (i32.or (i32.lt_u (local.get $i) (i32.const {dst}))
                      (i32.ge_u (local.get $i) (i32.const {dst+cap})))
        (then
          (if (i32.and (i32.ge_u (local.get $i) (i32.const {src}))
                       (i32.lt_u (local.get $i) (i32.const {src+len(block)})))
            (then
              (block $done
'''
        for j, b in enumerate(block):
            text += f'                (if (i32.eq (local.get $i) (i32.const {src+j})) (then (if (i32.ne (i32.load8_u (local.get $i)) (i32.const {b})) (then unreachable)) (br $done)))\n'
        text += '''              ))
            (else (if (i32.ne (i32.load8_u (local.get $i)) (i32.const 165)) (then unreachable))))))
      (local.set $i (i32.add (local.get $i) (i32.const 1)))
      (br_if $scan (i32.lt_u (local.get $i) (i32.const 2097152))))
    (i32.const 1))
'''
    text += ')\n'
    for i, c in enumerate(CASES):
        text += f';; {c["name"]}\n(assert_return (invoke $tests "case{i}") (i32.const 1))\n'
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--wasmtime', action='store_true')
    args = parser.parse_args()
    extract()  # Pin the artifact and verify its interface before doing anything.
    target = ROOT / 'Proofs/Cases.lean'
    if args.check:
        assert target.read_text() == lean_data(), 'case data mismatch'
        print(f'PASS: {len(CASES)} generated case statements match')
    else:
        target.write_text(lean_data())
        print('Wrote', target.relative_to(ROOT))
    if args.wasmtime:
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / 'checks.wast'
            path.write_text(wast())
            subprocess.run(['wasmtime', 'wast', '-C', 'cache=n', str(path)], check=True)
        print(f'PASS: Wasmtime, {len(CASES)} exact-artifact executions; outputs and arena write canaries')
