#!/usr/bin/env python3
"""Reproducibly quote the unmodified binary and its reachable function instructions."""
from pathlib import Path
import hashlib, sys
EXPECTED = '8b73efb63f0467d9999d867007969b75826140dce9e5677bd0439dc6af384ac6'
binary = Path('lz4-c.wasm').read_bytes()
assert len(binary) == 8469 and hashlib.sha256(binary).hexdigest() == EXPECTED

def leb(bs, p, signed=False):
    n = shift = 0
    while True:
        b = bs[p]; p += 1
        n |= (b & 127) << shift; shift += 7
        if b < 128:
            if signed and b & 64: n -= 1 << shift
            return n, p

def sections(bs):
    assert bs[:8] == b'\0asm\1\0\0\0'
    p, out = 8, {}
    while p < len(bs):
        tag = bs[p]; size, p = leb(bs, p+1)
        assert tag not in out
        out[tag] = bs[p:p+size]; p += size
    assert p == len(bs)
    return out

ss = sections(binary)
assert set(ss) == {1,3,5,6,7,10,11}  # no imports, table, start, custom sections
n, p = leb(ss[10], 0); bodies = []
for _ in range(n):
    size, p = leb(ss[10], p)
    bodies.append(ss[10][p:p+size]); p += size
assert p == len(ss[10]) and n == 6

def function(bs):
    groups, p = leb(bs, 0); assert groups == 1
    locals_, p = leb(bs, p); assert bs[p] == 127; p += 1
    out = []
    while p < len(bs):
        op = bs[p]; p += 1; a = b = 0
        if op in (2,3):
            assert bs[p] == 64; p += 1
        elif op in (12,13,16,32,33,34): a, p = leb(bs,p)
        elif op in (40,45,47,54,58):
            a, p = leb(bs,p); b, p = leb(bs,p)
        elif op == 65:
            a, p = leb(bs,p,True); a %= 1 << 32
        else: assert op in (11,15,26,27,69,70,71,72,73,75,77,79,106,107,113,115,116,118)
        out.append((op,a,b))
    return locals_, out

funcs = [function(bodies[i]) for i in (2,3,4)]
# Fixed signatures, memory, global, exports and active data segment are checked again in Lean.
assert ss[1] == bytes([3,96,6,127,127,127,127,127,127,1,127,96,4,127,127,127,127,1,127,96,3,127,127,127,1,127])
assert ss[3] == bytes([6,0,1,1,2,2,2])
assert ss[5] == bytes([1,1,32,32])
assert ss[6] == bytes([1,127,1,65,128,128,4,11])
assert ss[7] == (b'\3\6memory\2\0\24LZ4_compress_default\0\1\23LZ4_decompress_safe\0\2')
assert ss[11][:8] == bytes([1,0,65,128,128,4,11,64])
assert len(ss[11]) == 72

def nums(bs): return '['+','.join(map(str,bs))+']'
lines = ['-- Generated by verification/generate.py. Do not edit.', 'import Proofs.Wasm',
         'set_option maxRecDepth 100000', 'set_option maxHeartbeats 0',
         'namespace Artifact', 'open Wasm', 'def bytes : Bytes := [']
for i in range(0,len(binary),32): lines.append('  '+','.join(map(str,binary[i:i+32]))+(',' if i+32<len(binary) else ''))
lines += [']', 'def functions : List Func := [']
for j,(locals_,code) in enumerate(funcs):
    lines += [f'  ⟨{locals_}, [']
    for i in range(0,len(code),8):
        lines.append('    '+','.join(f'⟨{op},{a},{b}⟩' for op,a,b in code[i:i+8])+(',' if i+8<len(code) else ''))
    lines += ['  ]⟩'+(',' if j<2 else '')]
lines += [']', 'def dataBytes : Bytes := '+nums(ss[11][8:]), 'theorem code_link : program bytes = some functions := by rfl',
          'def metadata : Option (List (Nat × Bytes)) := do',
          '  let ss ← sections bytes',
          '  pure (ss.filter fun s => s.1 != 10)',
          'theorem metadata_link : metadata = some [']
for i,tag in enumerate([1,3,5,6,7,11]):
    payload = nums(ss[tag]) if tag != 11 else nums(ss[tag][:8])+' ++ dataBytes'
    lines.append(f'  ({tag}, {payload})'+(',' if i<5 else ''))
lines += ['] := by rfl', 'end Artifact', '']
text = '\n'.join(lines)
path = Path('Proofs/Artifact.lean')
if '--check' in sys.argv:
    assert path.read_text() == text, 'Artifact.lean is stale or was modified'
else: path.write_text(text)
print('Artifact quoted: 8469 bytes, sha256 '+EXPECTED)
