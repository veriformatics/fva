#!/usr/bin/env python3
"""Fail-closed decoder-body extraction; no Rust build or WAT parser involved."""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
EXPECTED = "1f115e3a5ddee865621f406e2abf545854218cb8dc632d759e998553031aa775"


class Reader:
    def __init__(self, data):
        self.data, self.pos = data, 0

    def byte(self):
        b = self.data[self.pos]
        self.pos += 1
        return b

    def take(self, n):
        assert self.pos + n <= len(self.data)
        b = self.data[self.pos:self.pos + n]
        self.pos += n
        return b

    def leb(self, signed=False):
        value, shift = 0, 0
        while True:
            b = self.byte()
            value |= (b & 127) << shift
            shift += 7
            assert shift <= 70
            if b < 128:
                return value - (1 << shift) if signed and b & 64 else value

    def done(self):
        assert self.pos == len(self.data)


def extract():
    raw = (ROOT / "lz4-flex.wasm").read_bytes()
    assert len(raw) == 7161 and hashlib.sha256(raw).hexdigest() == EXPECTED
    r = Reader(raw)
    assert r.take(8) == b"\0asm\x01\0\0\0"
    sections = {}
    while r.pos < len(raw):
        ident, length = r.byte(), r.leb()
        content = r.take(length)
        if ident:
            assert ident not in sections
            sections[ident] = content
    assert 2 not in sections  # no imported functions or memories
    r = Reader(sections[5])
    assert [r.leb() for _ in range(4)] == [1, 1, 32, 32]
    r.done()
    r = Reader(sections[7])
    exports = {}
    for _ in range(r.leb()):
        name = r.take(r.leb()).decode()
        exports[name] = (r.byte(), r.leb())
    r.done()
    assert exports["lz4_decompress"] == (0, 7)
    assert exports["memory"] == (2, 0)
    r = Reader(sections[3])
    types = [r.leb() for _ in range(r.leb())]
    r.done()
    assert len(types) == 9 and types[7] == 4
    r = Reader(sections[1])
    signatures = []
    for _ in range(r.leb()):
        assert r.byte() == 0x60
        params = [r.byte() for _ in range(r.leb())]
        results = [r.byte() for _ in range(r.leb())]
        signatures.append((params, results))
    r.done()
    assert signatures[4] == ([0x7f] * 4, [0x7f])
    r = Reader(sections[10])
    bodies = [r.take(r.leb()) for _ in range(r.leb())]
    r.done()
    assert len(bodies) == 9
    r = Reader(bodies[7])
    locals_ = []
    for _ in range(r.leb()):
        count, typ = r.leb(), r.byte()
        locals_ += [typ] * count
    assert locals_ == [0x7f] * 17 + [0x7e] * 7
    plain = {
        0x00: ".unreachable", 0x0b: ".endBlock", 0x0f: ".ret",
        0x1b: ".select", 0x45: ".eqz", 0x46: ".bin .eq",
        0x47: ".bin .ne", 0x49: ".bin .lt", 0x4b: ".bin .gt",
        0x4d: ".bin .le", 0x4f: ".bin .ge", 0x6a: ".bin .add",
        0x6b: ".bin .sub", 0x71: ".bin .and", 0x76: ".bin .shr",
    }
    indexed = {0x0c: "br", 0x0d: "brIf", 0x10: "call",
               0x20: "get", 0x21: "set", 0x22: "tee"}
    mem = {0x28: ("load", 4), 0x29: ("load", 8),
           0x2d: ("load", 1), 0x2f: ("load", 2),
           0x36: ("store", 4), 0x37: ("store", 8),
           0x3a: ("store", 1), 0x3b: ("store", 2)}
    instructions, blocks = [], []
    while r.pos < len(r.data):
        op = r.byte()
        if op in plain:
            ins = plain[op]
            if op == 0x0b and blocks:
                start, kind = blocks.pop()
                instructions[start] = f".{kind} {len(instructions) + 1}"
        elif op in indexed:
            ins = f".{indexed[op]} {r.leb()}"
        elif op == 0x41:
            ins = f".const {r.leb(signed=True) % (1 << 32)}"
        elif op in (0x02, 0x03):
            assert r.byte() == 0x40  # only empty block signatures
            blocks.append((len(instructions), "block" if op == 2 else "loop"))
            ins = "UNRESOLVED"
        elif op in mem:
            kind, width = mem[op]
            alignment, offset = r.leb(), r.leb()
            assert 1 << alignment <= width
            ins = f".{kind} {width} {offset}"
        elif op == 0xfc:
            subop = r.leb()
            if subop == 10:
                assert r.leb() == 0 and r.leb() == 0
                ins = ".copy"
            elif subop == 11:
                assert r.leb() == 0
                ins = ".fill"
            else:
                raise ValueError(f"unsupported extended opcode {subop}")
        else:
            raise ValueError(f"unsupported opcode {op:#x}")
        instructions.append(ins)
    assert not blocks and instructions[-1] == ".endBlock"
    content = ["-- Generated by verification/extract.py from the digest-checked artifact.",
               "import Proofs.Wasm", "namespace Artifact", "open Wasm", "",
               f'def sha256 : String := "{EXPECTED}"',
               f"def localCount : Nat := {4 + len(locals_)}",
               "def decoder : Array Instr := #["]
    content += [f"  {ins}{',' if i + 1 < len(instructions) else ''} -- {i}"
                for i, ins in enumerate(instructions)]
    content += ["]", "end Artifact", ""]
    return "\n".join(content)


if __name__ == "__main__":
    content = extract()
    target = ROOT / "Proofs/Artifact.lean"
    if sys.argv[1:] == ["--check"]:
        assert target.read_text() == content, "generated artifact model is stale"
        print("PASS: exact artifact digest, interface, and extracted decoder")
    else:
        assert not sys.argv[1:]
        target.write_text(content)
        print("wrote Proofs/Artifact.lean")
