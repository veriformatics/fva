#!/usr/bin/env python3
"""Extract the decoder's structured instructions directly from the pinned binary.

Unknown instruction encodings are rejected, not skipped. Round-trip the extracted
function including local declarations before producing Lean data.
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPECTED = "8b73efb63f0467d9999d867007969b75826140dce9e5677bd0439dc6af384ac6"


class Reader:
    def __init__(self, data):
        self.data, self.pos = data, 0

    def take(self, n):
        assert self.pos + n <= len(self.data), "truncated binary"
        result = self.data[self.pos:self.pos + n]
        self.pos += n
        return result

    def byte(self):
        return self.take(1)[0]

    def leb(self):
        value, shift = 0, 0
        while True:
            b = self.byte()
            value |= (b & 127) << shift
            shift += 7
            assert shift <= 35
            if b < 128:
                return value

    def done(self):
        assert self.pos == len(self.data), "unconsumed binary"


def uleb(n, width=0):
    out = bytearray()
    while n >= 128 or len(out) + 1 < width:
        out.append((n & 127) | 128)
        n >>= 7
    return bytes(out + bytes([n]))


def instructions(r):
    nodes, encoded = [], bytearray()
    while True:
        op = r.byte()
        encoded.append(op)
        if op == 0x0B:
            return nodes, bytes(encoded)
        if op in (2, 3):
            assert r.byte() == 0x40, "nonempty block type"
            body, raw = instructions(r)
            nodes.append(("block" if op == 2 else "loop", body))
            encoded += b"\x40" + raw
        else:
            if op in (0x0C, 0x0D, 0x10, 0x20, 0x21, 0x22):
                start = r.pos
                args = [r.leb()]
                encoded += uleb(args[0], r.pos - start)
            elif op == 0x41:
                start = r.pos
                n = r.leb()
                raw = r.data[start:r.pos]
                if raw[-1] & 0x40:
                    n -= 1 << (7 * len(raw))
                args = [n % (1 << 32)]
                encoded += raw
            elif op in (0x28, 0x2D, 0x2F, 0x36, 0x3A):
                start = r.pos
                align = r.leb()
                width = r.pos - start
                start = r.pos
                offset = r.leb()
                args = [align, offset]
                encoded += uleb(align, width) + uleb(offset, r.pos - start)
            else:
                assert op in (0x0F, 0x1A, 0x1B, 0x45, 0x46, 0x47,
                              0x48, 0x49, 0x4B, 0x4D, 0x4F, 0x6A,
                              0x6B, 0x71, 0x73, 0x74, 0x76), hex(op)
                args = []
            nodes.append(("op", op, args))


def render(nodes, indent=2):
    lines = []
    for node in nodes:
        if node[0] == "op":
            lines.append(" " * indent + f".op {node[1]} {node[2]}")
        else:
            lines.append(" " * indent + f".{node[0]} [\n" +
                         render(node[1], indent + 2) + "\n" + " " * indent + "]")
    return ",\n".join(lines)


def extract():
    artifact = (ROOT / "lz4-c.wasm").read_bytes()
    assert len(artifact) == 8469
    assert hashlib.sha256(artifact).hexdigest() == EXPECTED, "artifact hash mismatch"
    r = Reader(artifact)
    assert r.take(8) == b"\0asm\x01\0\0\0"
    sections = {}
    while r.pos < len(artifact):
        tag, size = r.byte(), r.leb()
        assert tag not in sections and tag != 0
        sections[tag] = r.take(size)
    assert set(sections) == {1, 3, 5, 6, 7, 10, 11}, "unexpected module shape"
    assert sections[1] == bytes.fromhex("0360067f7f7f7f7f7f017f60047f7f7f7f017f60037f7f7f017f")
    assert sections[3] == bytes.fromhex("06000101020202")
    assert sections[5] == bytes.fromhex("01012020")  # fixed 32 pages
    exports = Reader(sections[7])
    result = {}
    for _ in range(exports.leb()):
        name = exports.take(exports.leb()).decode("ascii")
        result[name] = (exports.byte(), exports.leb())
    exports.done()
    assert result == {"memory": (2, 0), "LZ4_compress_default": (0, 1),
                      "LZ4_decompress_safe": (0, 2)}
    code = Reader(sections[10])
    assert code.leb() == 6
    bodies = [code.take(code.leb()) for _ in range(6)]
    code.done()
    body = Reader(bodies[2])
    assert body.leb() == 1 and body.leb() == 15 and body.byte() == 0x7F
    nodes, raw = instructions(body)
    body.done()
    assert b"\x01\x0f\x7f" + raw == bodies[2], "function round trip failed"
    text = ("-- Generated by verification/extract.py; do not edit.\n"
            "import Proofs.Semantics\n\nnamespace Artifact\n"
            "def decoder : List Instr := [\n" + render(nodes) + "\n]\n"
            "end Artifact\n")
    return text


if __name__ == "__main__":
    import sys
    text = extract()
    target = ROOT / "Proofs/Artifact.lean"
    if sys.argv[1:] == ["--check"]:
        assert target.read_text() == text, "stale or modified Lean instruction data"
        print("Artifact SHA-256, module shape, extraction and round trip: PASS")
    else:
        assert not sys.argv[1:]
        target.write_text(text)
