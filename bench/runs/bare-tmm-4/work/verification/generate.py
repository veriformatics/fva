"""Propose Lean certificates, or check that they still describe the shipped bytes.

Decimal.ln proposes bounds only. Lean's log-series theorem checks every bound
using exact rational arithmetic. --check does not rewrite any source or artifact.
"""
from decimal import Decimal, localcontext, ROUND_FLOOR
from fractions import Fraction as Q
import json
from pathlib import Path
import subprocess
import tempfile
from replay import run

if not __debug__:
    raise RuntimeError("Verification requires Python assertions enabled")

INPUTS = ["counts.tsv", "edger-factors.txt", "rnanorm-factors.txt",
          "edger-factors.R", "rnanorm-factors.py", "README.md",
          "edgeR/R/normLibSizes.R", "edgeR/R/calcNormFactors.R",
          "edgeR/man/calcNormFactors.Rd", "rnanorm/between_sample.py", "rnanorm/utils.py"]
TOL = Q(1, 10**12)


def rat(q):
    q = Q(q)
    return f"({q.numerator} / {q.denominator})"


def dec(q):
    return Decimal(q.numerator) / Decimal(q.denominator)


def interval(x, digits):
    k = int((x * 10**digits).to_integral_value(rounding=ROUND_FLOOR))
    return Q(k, 10**digits), Q(k + 1, 10**digits)


def model(rows, lib, masks):
    result = []
    for i, ids in enumerate(masks):
        terms = []
        for g in ids:
            o, r = rows[g - 1][i], rows[g - 1][3]
            assert o > 0 and r > 0
            # Exact-real delta-method inverse-variance weight from both sources.
            weight = 1 / (Q(1, o) - Q(1, lib[i]) + Q(1, r) - Q(1, lib[3]))
            ratio = Q(o * lib[3], r * lib[i])
            terms.append((ratio, weight))
        total = sum(w for _, w in terms)
        assert total > 0
        result.append(([(q, w / total) for q, w in terms], [(w, q) for q, w in terms], total))
    return result


def generate():
    rows = [list(map(int, line.split("\t")))
            for line in Path("counts.tsv").read_text().splitlines()]
    assert len(rows) == 454 and all(len(r) == 7 for r in rows)
    assert all(x >= 0 for r in rows for x in r)
    assert all(any(r) for r in rows)  # gene indices are unchanged by remove_zero_genes
    lib = [sum(r[i] for r in rows) for i in range(7)]
    assert lib == [1261, 621, 755, 1097, 1916, 1136, 1219]
    # Exact type-7 upper quartiles: h=(454-1)*3/4=339+3/4 (zero based).
    quartiles = []
    for i in range(7):
        col = sorted(r[i] for r in rows)
        quartiles.append((Q(col[339], 4) + Q(3 * col[340], 4)) / lib[i])
    mean = sum(quartiles) / 7
    assert min(range(7), key=lambda i: abs(quartiles[i] - mean)) == 3
    with tempfile.TemporaryDirectory() as tmp:
        mask_file = Path(tmp) / "masks.txt"
        subprocess.run(["Rscript", "verification/replay.R", str(mask_file)], check=True)
        edge_masks = [[int(g) for g in s.split(",")]
                      for s in mask_file.read_text().splitlines()]
    rna_masks = run()
    assert len(edge_masks) == len(rna_masks) == 7
    assert set(edge_masks[0]) - set(rna_masks[0]) == {355}
    assert set(rna_masks[0]) <= set(edge_masks[0])
    assert all(edge_masks[i] == rna_masks[i] for i in [1, 2, 4, 5, 6])
    assert rows[162][0] * rows[162][3] == rows[354][0] * rows[354][3] == 104
    masks = {"edge": edge_masks, "rna": rna_masks}
    bundles = {name: model(rows, lib, mm) for name, mm in masks.items()}
    models = {name: [b[0] for b in bb] for name, bb in bundles.items()}
    values = {name: [Q(s) for s in Path(file).read_text().splitlines()]
              for name, file in [("edge", "edger-factors.txt"),
                                 ("rna", "rnanorm-factors.txt")]}
    assert all(len(v) == 7 for v in values.values())

    all_q = {q for model_ in models.values() for terms in model_ for q, _ in terms}
    all_q |= {v + sign * TOL for vs in values.values() for v in vs for sign in [-1, 1]}
    logs = sorted(all_q)
    log_ids = {q: f"log_{j:03d}" for j, q in enumerate(logs)}
    cert = ["-- Generated by verification/generate.py; do not edit.",
            "import Proofs.Intervals", "import Proofs.InputData", "set_option maxRecDepth 1000000",
            "set_option maxHeartbeats 0", "namespace Verification"]
    weights = sorted({w for bb in bundles.values() for b in bb
                      for w in [b[2], *[w for _, w in b[0]], *[w for w, _ in b[1]]]})
    weight_ids = {w: f"weight_{j:03d}" for j, w in enumerate(weights)}
    cert += [f"def {weight_ids[w]} : ℚ := {rat(w)}" for w in weights]
    with localcontext() as ctx:
        ctx.prec = 80
        for q in logs:
            lo, hi = interval(dec(q).ln(), 18)
            cert += [f"def {log_ids[q]} : LogBounds := {{",
                     f"  q := {rat(q)}", "  positive := by norm_num",
                     f"  lo := {rat(lo)}", f"  hi := {rat(hi)}",
                     "  sound := log_check_sound _ _ _ 24 (by decide +kernel) }"]
        raw_intervals = {}
        for name, mm in models.items():
            raw_intervals[name] = []
            for i, terms in enumerate(mm):
                val = sum(dec(w) * dec(q).ln() for q, w in terms)
                lo, hi = interval(val, 16)
                raw_intervals[name].append((lo, hi))
                ts = ",\n    ".join(f"({weight_ids[w]}, {log_ids[q]})" for q, w in terms)
                inp = ",\n    ".join(f"({weight_ids[w]}, {log_ids[q]}.q)" for w, q in bundles[name][i][1])
                total = bundles[name][i][2]
                cert += [f"def {name}Input{i} : List (ℚ × ℚ) := [\n    {inp}]",
                         f"theorem {name}Input{i}_from_counts : {name}Input{i} =",
                         f"    {name}Mask{i}.map (geneTerm counts {i}) := by",
                         "  unfold geneTerm", "  simp only [library_sizes]", "  decide +kernel",
                         f"theorem {name}Weight{i} : ({name}Input{i}.map Prod.fst).sum = {weight_ids[total]} := by decide +kernel"]
                cert += [f"def {name}Terms{i} : List Term := [\n    {ts}]",
                         f"theorem {name}Raw{i} : (({rat(lo)} : ℚ) : ℝ) ≤ value {name}Terms{i} ∧",
                         f"    value {name}Terms{i} ≤ (({rat(hi)} : ℚ) : ℝ) :=",
                         f"  value_between {name}Terms{i} {rat(lo)} {rat(hi)} (by decide +kernel) (by decide +kernel)"]
    for name in models:
        for i in range(7):
            cert += [f"theorem {name}Terms{i}_from_counts :",
                     f"    ({name}Terms{i}.map fun t => (t.1, t.2.q)) =",
                     f"      selectedTerms counts {i} {name}Mask{i} := by",
                     f"  simp only [selectedTerms, ← {name}Input{i}_from_counts, {name}Weight{i}]",
                     "  decide +kernel"]
        cert += [f"noncomputable def {name}Raw : Fin 7 → ℝ :=",
                 "  ![" + ", ".join(f"value {name}Terms{i}" for i in range(7)) + "]",
                 f"def {name}Lo : Fin 7 → ℚ :=",
                 "  ![" + ", ".join(rat(p[0]) for p in raw_intervals[name]) + "]",
                 f"def {name}Hi : Fin 7 → ℚ :=",
                 "  ![" + ", ".join(rat(p[1]) for p in raw_intervals[name]) + "]",
                 f"theorem {name}Raw_bounds : ∀ i, ({name}Lo i : ℝ) ≤ {name}Raw i ∧",
                 f"    {name}Raw i ≤ ({name}Hi i : ℝ) := by",
                 "  intro i", "  fin_cases i"]
        cert += [f"  · exact {name}Raw{i}" for i in range(7)]
    for name in models:
        cert += [f"theorem {name}Raw_from_counts : {name}Raw = selectedRaw counts {name}Masks := by",
                 "  funext i", "  fin_cases i"]
        for i in range(7):
            cert += [f"  · change value {name}Terms{i} = rationalValue (selectedTerms counts {i} {name}Mask{i})",
                     f"    rw [value_projection, {name}Terms{i}_from_counts]"]
    cert += ["end Verification", ""]

    artifact = ["-- Exact decimal text and rational parsing of the shipped factor files.",
                "import Proofs.Parsing", "set_option maxRecDepth 1000000",
                "namespace Verification"]
    for name, file in [("edge", "edger-factors.txt"), ("rna", "rnanorm-factors.txt")]:
        artifact += [f"def {name}Bytes : String := {json.dumps(Path(file).read_text())}",
                     f"def {name}Values : Fin 7 → ℚ :=",
                     "  ![" + ", ".join(rat(v) for v in values[name]) + "]"]
    for name in models:
        artifact += [f"theorem {name}_parses : parseFactors {name}Bytes =",
                     f"    some (List.ofFn {name}Values) := by decide +kernel"]
    artifact += ["def round10 (q : ℚ) : ℤ := ⌊q * 10^10 + 1/2⌋",
                 "theorem R3_gap : ∀ i : Fin 7, (1/1000 : ℚ) < |edgeValues i - rnaValues i| := by",
                 "  intro i; fin_cases i <;> norm_num [edgeValues, rnaValues]",
                 "theorem R3_rounding : ∀ i : Fin 7, round10 (edgeValues i) ≠ round10 (rnaValues i) := by",
                 "  decide +kernel", "end Verification", ""]

    results = ["import Proofs.Certificates", "import Proofs.Artifacts",
               "set_option maxRecDepth 1000000", "set_option maxHeartbeats 0",
               "namespace Verification"]
    for name, req in [("edge", "R1"), ("rna", "R2")]:
        results += [f"theorem {req}_model : ∀ i : Fin 7,",
                    f"    |factor {name}Raw i - ({name}Values i : ℝ)| ≤ ((1/10^12 : ℚ) : ℝ) := by",
                    "  intro i", "  fin_cases i"]
        for i, v in enumerate(values[name]):
            results += [f"  · exact factor_near {name}Raw {name}Lo {name}Hi {name}Raw_bounds {i}",
                        f"      {log_ids[v-TOL]} {log_ids[v+TOL]} ({name}Values {i}) (1/10^12)",
                        "      (by decide +kernel) (by decide +kernel) (by decide +kernel) (by decide +kernel)"]
    for name, req in [("edge", "R1"), ("rna", "R2")]:
        results += [f"theorem {req}_selected_TMM : ∀ i : Fin 7,",
                    f"    |selectedTMM counts {name}Masks i - ({name}Values i : ℝ)| ≤ ((1/10^12 : ℚ) : ℝ) := by",
                    f"  simpa only [selectedTMM, ← {name}Raw_from_counts] using {req}_model"]
    results += ["#print axioms R1_selected_TMM", "#print axioms R2_selected_TMM", "#print axioms R1_model", "#print axioms R2_model",
                "#print axioms R3_gap", "#print axioms R3_rounding",
                "end Verification", ""]
    data = ["-- The matrix and observed trimming masks, bound to input text below.",
            "import Proofs.Model", "set_option maxRecDepth 1000000",
            "set_option maxHeartbeats 0", "namespace Verification",
            "def countLines : List String := [" + ", ".join(json.dumps(line) for line in Path("counts.tsv").read_text().splitlines()) + "]",
            "def counts : List (List ℕ) := [",
            ",\n".join("  [" + ", ".join(map(str, row)) + "]" for row in rows), "]",
            "theorem counts_parses : List.Forall₂ (fun s row => (splitChars '\\t' s.toList).mapM digits = some row) countLines counts := by decide +kernel",
            "theorem counts_shape : counts.length = 454 ∧ (∀ r ∈ counts, r.length = 7) := by decide +kernel",
            "theorem no_zero_rows : ∀ r ∈ counts, r ≠ List.replicate 7 0 := by decide +kernel",
            "theorem library_sizes : librarySizes counts = ![1261, 621, 755, 1097, 1916, 1136, 1219] := by",
            "  funext i; fin_cases i <;> decide +kernel",
            "theorem upper_quartiles : upperQuartiles counts =",
            "    ![4/1261, 2/621, 2/755, 3/1097, 5/1916, 3/1136, 3/1219] := by",
            "  funext i; fin_cases i <;> decide +kernel",
            "theorem reference_closest : ∀ i : Fin 7, i ≠ 3 →",
            "    |upperQuartiles counts 3 - (∑ j, upperQuartiles counts j)/7| <",
            "    |upperQuartiles counts i - (∑ j, upperQuartiles counts j)/7| := by",
            "  rw [upper_quartiles]", "  decide +kernel"]
    for name, mm in masks.items():
        for i, ids in enumerate(mm):
            data += [f"def {name}Mask{i} : List ℕ := [" + ", ".join(map(str, ids)) + "]",
                     f"theorem {name}Mask{i}_valid :",
                     f"    {name}Mask{i}.Nodup ∧ ∀ g ∈ {name}Mask{i}, 1 ≤ g ∧ g ≤ 454 ∧",
                     f"      0 < (geneTerm counts {i} g).1 ∧ 0 < (geneTerm counts {i} g).2 := by",
                     "  simp only [geneTerm, library_sizes]",
                     "  decide +kernel"]
    for name in masks:
        data += [f"def {name}Masks : Fin 7 → List ℕ :=",
                 "  ![" + ", ".join(f"{name}Mask{i}" for i in range(7)) + "]"]
    data += ["end Verification", ""]
    generated = {"Proofs/InputData.lean": "\n".join(data), "Proofs/Artifacts.lean": "\n".join(artifact),
                 "Proofs/Certificates.lean": "\n".join(cert),
                 "Proofs/Results.lean": "\n".join(results),
                 "verification/masks.json": json.dumps(masks, indent=2) + "\n"}
    return generated


def main():
    mode = sys.argv[1] if len(sys.argv) == 2 else None
    if mode not in ["--write", "--check"]:
        raise SystemExit("usage: python3 verification/generate.py --write|--check")
    manifest_path = Path("verification/inputs.json")
    if mode == "--check":
        manifest = json.loads(manifest_path.read_text())
        assert set(manifest) == set(INPUTS)
        for path, expected in manifest.items():
            assert Path(path).read_bytes() == bytes.fromhex(expected), f"changed input: {path}"
    generated = generate()
    if mode == "--write":
        for path, content in generated.items():
            Path(path).write_text(content)
        manifest_path.write_text(json.dumps({p: Path(p).read_bytes().hex() for p in INPUTS}, indent=2) + "\n")
        print("Wrote exact-input manifest, masks, and Lean certificates.")
    else:
        for path, content in generated.items():
            assert Path(path).read_text() == content, f"generated model differs: {path}"
        print("PASS: exact input bytes, source replays, masks, and generated Lean models agree.")


if __name__ == "__main__":
    import sys
    main()
