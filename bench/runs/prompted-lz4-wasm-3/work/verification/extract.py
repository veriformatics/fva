#!/usr/bin/env python3
"""Extract structured instruction trees directly from the shipped binary.
Only the opcode subset in this artifact is accepted; no source WAT is read.
"""
from pathlib import Path
import hashlib

ARTIFACT = Path('lz4-block-codec.wasm')
SHA256 = '4bda6947a0498618552cba53ab3780745fd34cc1a0d84696e83a0547dcd68acf'
class Reader:
    def __init__(self, data): self.data, self.pos = data, 0
    def byte(self):
        x = self.data[self.pos]; self.pos += 1; return x
    def take(self, n):
        x = self.data[self.pos:self.pos+n]; self.pos += n
        assert len(x) == n
        return x
    def leb(self, signed=False):
        x = shift = 0
        while True:
            b = self.byte(); x |= (b & 127) << shift; shift += 7
            if b < 128: break
        return x - (1 << shift) if signed and b & 64 else x
    def done(self): assert self.pos == len(self.data)

def instructions(r):
    out = []
    while True:
        op = r.byte()
        if op in (0x05, 0x0b): return out, op
        if op in (2, 3, 4):
            assert r.byte() == 0x40  # only empty block signatures
            body, end = instructions(r)
            if op == 4:
                other = []
                if end == 5: other, end = instructions(r)
                assert end == 11
                out.append(f'.ite {fmt(body)} {fmt(other)}')
            else:
                assert end == 11
                out.append(f'.{ "block" if op == 2 else "loop"} {fmt(body)}')
        else:
            imm = 0
            if op in (12, 13, 16, 32, 33, 34): imm = r.leb()
            elif op == 65: imm = r.leb(True) % (1 << 32)
            elif op in (40, 45, 54, 58):
                align = r.leb(); assert align <= (2 if op in (40, 54) else 0)
                imm = r.leb()
            else:
                assert op in (0, 15, 27, 69, 70, 71, 73, 74, 75, 78, 79,
                              106, 107, 108, 110, 113, 114, 116, 118), hex(op)
            out.append(f'.op {op} {imm}')

def fmt(xs): return '[' + ', '.join(xs) + ']'

def extract():
    data = ARTIFACT.read_bytes()
    assert len(data) == 1226 and hashlib.sha256(data).hexdigest() == SHA256
    r = Reader(data); assert r.take(8) == b'\0asm\1\0\0\0'
    sections = {}
    while r.pos < len(data):
        tag = r.byte(); body = r.take(r.leb())
        assert tag not in sections
        sections[tag] = body
    assert set(sections) == {1, 3, 5, 7, 10}
    t = Reader(sections[1]); types = []
    for _ in range(t.leb()):
        assert t.byte() == 0x60
        ps = t.take(t.leb()); rs = t.take(t.leb())
        assert all(x == 0x7f for x in ps + rs) and len(rs) <= 1
        types.append((len(ps), len(rs)))
    t.done()
    f = Reader(sections[3]); signatures = [types[f.leb()] for _ in range(f.leb())]; f.done()
    m = Reader(sections[5]); assert m.leb() == 1 and m.byte() == 0 and m.leb() == 1; m.done()
    e = Reader(sections[7]); exports = {}
    for _ in range(e.leb()):
        name = e.take(e.leb()).decode(); exports[name] = (e.byte(), e.leb())
    e.done()
    assert exports == {'memory': (2, 0), 'getLinearMemoryOffset': (0, 0),
                       'lz4BlockEncodeBound': (0, 1), 'lz4BlockEncode': (0, 2),
                       'lz4BlockDecode': (0, 3)}
    c = Reader(sections[10]); assert c.leb() == len(signatures)
    lines = ['-- Generated by verification/extract.py from the SHA-256-pinned Wasm.',
             'import Proofs.Wasm', 'namespace Verification',
             'def artifact : List Fn := [']
    for i, (np, nr) in enumerate(signatures):
        b = Reader(c.take(c.leb())); nl = 0
        for _ in range(b.leb()):
            nl += b.leb(); assert b.byte() == 0x7f
        body, end = instructions(b); assert end == 11; b.done()
        lines.append(f'  ⟨{np}, {nr}, {nl}, {fmt(body)}⟩' + (',' if i+1 < len(signatures) else ''))
    c.done(); lines += [']', 'end Verification', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    import sys
    target = Path('Proofs/Artifact.lean')
    generated = extract()
    if '--check' in sys.argv:
        assert target.read_text() == generated, 'artifact extraction is stale'
    else: target.write_text(generated)
