"""Bind generated proof inputs to the shipped Wasm; no source compilation."""
from pathlib import Path
import hashlib

if not __debug__:
    raise RuntimeError('Run without Python assertion optimization')

ROOT = Path(__file__).resolve().parents[1]
EXPECTED = '8b73efb63f0467d9999d867007969b75826140dce9e5677bd0439dc6af384ac6'

class Reader:
    def __init__(self, data):
        self.data, self.pos = data, 0
    def byte(self):
        b = self.data[self.pos]
        self.pos += 1
        return b
    def uint(self):
        n, shift = 0, 0
        while True:
            b = self.byte()
            n |= (b & 127) << shift
            if b < 128:
                return n
            shift += 7
            assert shift < 35
    def take(self, n):
        b = self.data[self.pos:self.pos+n]
        assert len(b) == n
        self.pos += n
        return b
    def vec(self, f):
        return [f() for _ in range(self.uint())]
    def name(self):
        return self.take(self.uint()).decode()
    def end(self):
        assert self.pos == len(self.data)

def extract():
    binary = (ROOT / 'lz4-c.wasm').read_bytes()
    assert len(binary) == 8469 and hashlib.sha256(binary).hexdigest() == EXPECTED
    r = Reader(binary)
    assert r.take(8) == b'\0asm\1\0\0\0'
    sections = {}
    while r.pos < len(binary):
        tag, size = r.byte(), r.uint()
        assert tag not in sections and tag in (1, 3, 5, 6, 7, 10, 11)
        sections[tag] = Reader(r.take(size))
    t = sections[1]
    def typ():
        assert t.byte() == 96
        return t.vec(t.byte), t.vec(t.byte)
    types = t.vec(typ)
    t.end()
    f = sections[3]
    typeids = f.vec(f.uint)
    f.end()
    m = sections[5]
    assert m.vec(lambda: (m.byte(), m.uint(), m.uint())) == [(1, 32, 32)]
    m.end()
    g = sections[6]
    assert g.take(len(g.data)) == bytes([1, 127, 1, 65, 128, 128, 4, 11])
    e = sections[7]
    exports = e.vec(lambda: (e.name(), e.byte(), e.uint()))
    assert exports == [('memory', 2, 0), ('LZ4_compress_default', 0, 1),
                       ('LZ4_decompress_safe', 0, 2)]
    e.end()
    c = sections[10]
    bodies = c.vec(lambda: c.take(c.uint()))
    c.end()
    assert len(bodies) == len(typeids) == 6
    funcs = []
    for i in (2, 3, 4):
        params, results = types[typeids[i]]
        assert params == [127] * (4 if i == 2 else 3) and results == [127]
        b = Reader(bodies[i])
        groups = b.vec(lambda: (b.uint(), b.byte()))
        assert all(ty == 127 for _, ty in groups)
        funcs.append((i, len(params), sum(n for n, _ in groups), b.take(len(b.data)-b.pos)))
    d = sections[11]
    assert d.uint() == 1 and d.byte() == 0 and d.byte() == 65
    assert d.uint() == 65536 and d.byte() == 11
    table = d.take(d.uint())
    d.end()
    assert len(table) == 64
    def leanlist(xs):
        return '[' + ', '.join(map(str, xs)) + ']'
    lines = ['-- Generated from the hash-pinned shipped artifact by verification/extract.py.',
             'namespace Artifact']
    for i, arity, nlocals, code in funcs:
        lines += [f'def arity{i} : Nat := {arity}', f'def locals{i} : Nat := {nlocals}',
                  f'def bytes{i} : List Nat := {leanlist(code)}']
    lines += [f'def table : List Nat := {leanlist(table)}', 'end Artifact', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    import sys
    path = ROOT / 'Proofs' / 'Artifact.lean'
    content = extract()
    if '--check' in sys.argv:
        assert path.read_text() == content, 'Artifact.lean differs from artifact extraction'
        print('artifact SHA-256, module layout, and generated bytes: OK')
    else:
        path.write_text(content)
