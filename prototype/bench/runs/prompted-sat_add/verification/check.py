#!/usr/bin/env python3
"""Offline, fail-closed verification; no downloaded packages or prebuilt proofs."""
import copy
from collections import Counter
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / '.verification'


def run(args, label, *, good=True, cwd=BUILD, stdout_file=None, env=None):
    """Timeouts, crashes, and parser errors never count as rejected false proofs."""
    result = subprocess.run([str(a) for a in args], cwd=cwd, env=env,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            timeout=180)
    output = result.stdout.decode(errors='replace')
    (BUILD / (label + '.log')).write_text(output)
    if stdout_file is not None:
        stdout_file.write_bytes(result.stdout)
    if good and result.returncode != 0:
        raise RuntimeError(f'{label} failed ({result.returncode}):\n{output[-6000:]}')
    if not good:
        if result.returncode != 1 or not any(s in output.lower() for s in
                ('type mismatch', 'application type mismatch', 'has type', 'failed to prove',
                 'unsolved goals', 'not definitionally equal', 'tactic `decide`')):
            raise RuntimeError(f'{label} did not reject for the expected reason: '
                               f'{result.returncode}\n{output[-6000:]}')
    return output


def embed(data):
    return ('-- Generated from the entire shipped sat_add.wasm; regenerated by check.sh.\n'
            'import Init\nnamespace SatAdd\ndef artifact : List Nat := [' +
            ','.join(map(str, data)) + ']\nend SatAdd\n')


def parse_export(path):
    objects = [json.loads(line) for line in path.read_text().splitlines()]
    names = {0: ''}
    exprs, decls = {}, {}
    for o in objects:
        if 'in' in o:
            key = 'str' if 'str' in o else 'num'
            item = o[key]
            prefix = names[item['pre']]
            names[o['in']] = (prefix + '.' if prefix else '') + str(item.get('str', item.get('i')))
        if 'ie' in o:
            exprs[o['ie']] = o
        for kind in ('axiom', 'def', 'thm', 'opaque', 'quot'):
            if kind in o:
                decls[names[o[kind]['name']]] = (kind, o[kind])
        if 'inductive' in o:
            for group in ('types', 'ctors', 'recs'):
                for item in o['inductive'][group]:
                    decls[names[item['name']]] = (group, item)
    return objects, names, exprs, decls


def audit(path):
    objects, names, exprs, decls = parse_export(path)
    axioms = sorted(name for name, (kind, _) in decls.items() if kind == 'axiom')
    if not set(axioms) <= {'propext', 'Quot.sound', 'Classical.choice'}:
        raise RuntimeError(f'unexpected proof assumptions: {axioms}')
    if 'SatAdd.artifact_correct' not in decls:
        raise RuntimeError('missing verification theorem')
    for name, (_, d) in decls.items():
        if d.get('isUnsafe') or d.get('safety', 'safe') != 'safe':
            raise RuntimeError(f'unsafe dependency: {name}')
    print(f'Proof closure: {len(decls)} declarations; axioms: {", ".join(axioms)}', flush=True)
    return len(decls), axioms


def review_size(path):
    """Conservative statement closure, including core definitions and their proofs."""
    _, _, _, decls = parse_export(path)
    sources = [ROOT / 'verification/Semantics.lean', ROOT / 'verification/Artifact.lean']
    lines = [line for p in sources for line in p.read_text().splitlines()
             if line.strip() and not line.lstrip().startswith('--')]
    statement = 'theorem artifact_correct : Requirements artifact'
    result = {'project_code_lines': len(lines) + 1,
              'project_code_bytes': sum(len((line + '\n').encode()) for line in lines) +
                                    len((statement + '\n').encode()),
              'embedded_artifact_bytes': 87,
              'statement_closure_declarations': len(decls),
              'statement_closure_kinds': dict(sorted(Counter(k for k, _ in decls.values()).items())),
              'statement_export_bytes': path.stat().st_size}
    (BUILD / 'review-declarations.txt').write_text(''.join(
        f'{kind}\t{name}\n' for name, (kind, _) in sorted(decls.items())))
    print(f'Review boundary: {result["project_code_lines"]} project code lines, '
          f'{result["project_code_bytes"]} UTF-8 bytes; '
          f'{len(decls)} declarations in conservative full closure', flush=True)
    return result


def false_exports(path):
    objects, names, exprs, decls = parse_export(path)
    ids = {s: n for n, s in names.items()}
    false_expr = next(n for n, o in exprs.items()
                      if o.get('const', {}).get('name') == ids['False'])
    bad_false = []
    for o in copy.deepcopy(objects):
        if o.get('thm', {}).get('name') == ids['controlTrue']:
            false_thm = o
            false_thm['thm']['type'] = false_expr  # False := True.intro
        else:
            bad_false.append(o)
    bad_false.append(false_thm)
    zero_type = exprs[decls['controlZero'][1]['type']]
    one_literal = exprs[decls['controlOne'][1]['type']]['app']['arg']
    # The type of controlZero is ((Eq Nat) 0) 0: change only its final argument.
    assert 'app' in zero_type
    new_type = copy.deepcopy(zero_type)
    new_type['ie'] = max(exprs) + 1
    new_type['app']['arg'] = one_literal
    bad_eq = []
    for o in copy.deepcopy(objects):
        if o.get('thm', {}).get('name') == ids['controlZero']:
            o['thm']['type'] = new_type['ie']  # 0 = 1 := Eq.refl 0
            eq_thm = o
        else:
            bad_eq.append(o)
    bad_eq.extend([new_type, eq_thm])
    paths = []
    for name, data in [('false', bad_false), ('zero-equals-one', bad_eq)]:
        target = BUILD / (name + '.ndjson')
        target.write_text(''.join(json.dumps(o, separators=(',', ':')) + '\n' for o in data))
        paths.append(target)
    return paths


def main():
    if BUILD.exists():
        shutil.rmtree(BUILD)
    BUILD.mkdir()
    prefix = Path(subprocess.check_output(['lean', '--print-prefix'], text=True).strip())
    tools = {name: prefix / 'bin' / name for name in
             ('lean', 'leanexport', 'leanchecker', 'leanchecker-paranoid', 'lean4lean')}
    for name, tool in tools.items():
        if not tool.is_file():
            raise RuntimeError(f'required offline tool not found: {tool}')
    version = run([tools['lean'], '--version'], 'version').strip()
    if 'version 4.35.0,' not in version:
        raise RuntimeError(f'expected Lean 4.35.0, got {version}')
    print(version, flush=True)
    original = {name: (ROOT / name).read_bytes() for name in ('sat_add.c', 'sat_add.wasm')}
    run(['clang', '--target=wasm32', '-O2', '-nostdlib', '-Wl,--no-entry',
         '-Wl,--strip-all', '-Wl,--export=sat_add', '-o', BUILD / 'rebuilt.wasm',
         ROOT / 'sat_add.c'], 'rebuild')
    if (BUILD / 'rebuilt.wasm').read_bytes() != original['sat_add.wasm']:
        raise RuntimeError('README build does not reproduce shipped sat_add.wasm')
    generated = embed(original['sat_add.wasm'])
    if generated != (ROOT / 'verification/Artifact.lean').read_text():
        raise RuntimeError('shipped artifact differs from the reviewed byte embedding')
    (BUILD / 'Artifact.lean').write_text(generated)
    for module in ('Semantics', 'Arithmetic', 'Proof', 'Controls'):
        shutil.copyfile(ROOT / 'verification' / (module + '.lean'), BUILD / (module + '.lean'))
    env = dict(os.environ, LEAN_PATH=str(BUILD))
    for module in ('Artifact', 'Semantics', 'Arithmetic', 'Proof', 'Controls'):
        run([tools['lean'], '-o', module + '.olean', module + '.lean'],
            'compile-' + module, env=env)
    print('Fresh Lean proofs and byte-for-byte C rebuild: PASS', flush=True)
    proofs = BUILD / 'proofs.ndjson'
    run([tools['leanexport'], 'Proof', '--', 'SatAdd.artifact_correct'],
        'export-proofs', env=env, stdout_file=proofs)
    count, axioms = audit(proofs)
    review = BUILD / 'review.ndjson'
    run([tools['leanexport'], 'Proof', '--', 'SatAdd.Requirements', 'SatAdd.artifact'],
        'export-review', env=env, stdout_file=review)
    sizes = review_size(review)
    controls = BUILD / 'controls.ndjson'
    run([tools['leanexport'], 'Controls', '--', 'controlTrue', 'controlFalseIdentity',
         'controlZero', 'controlOne'], 'export-controls', env=env, stdout_file=controls)
    negatives = false_exports(controls)
    for name in ('leanchecker', 'leanchecker-paranoid', 'lean4lean'):
        mode = '--import' if name == 'lean4lean' else '--from-export'
        for label, file in [('positive-control', controls), ('proofs', proofs)]:
            run([tools[name], mode, file], name + '-' + label, env=env)
        for file in negatives:
            run([tools[name], mode, file], name + '-reject-' + file.stem,
                good=False, env=env)
        print(name + ': proofs accepted; both false proof terms rejected', flush=True)
    # Ensure a source-level false proof is rejected too.
    (BUILD / 'FalseSource.lean').write_text('theorem falseSource : False := True.intro\n')
    run([tools['lean'], 'FalseSource.lean'], 'reject-false-source', good=False, env=env)
    # Change a SUPPORTED opcode: i32.add -> i32.xor; recompile the ORIGINAL proof.
    mutant = bytearray(original['sat_add.wasm'])
    assert mutant[59] == 0x6a
    mutant[59] = 0x73
    (BUILD / 'Artifact.lean').write_text(embed(mutant))
    run([tools['lean'], '-o', 'Artifact.olean', 'Artifact.lean'], 'compile-mutant', env=env)
    run([tools['lean'], '-o', 'MutantProof.olean', 'Proof.lean'],
        'reject-mutant', good=False, env=env)
    (BUILD / 'Artifact.lean').write_text(generated)
    run([tools['lean'], '-o', 'Artifact.olean', 'Artifact.lean'], 'restore-artifact', env=env)
    for name, data in original.items():
        if (ROOT / name).read_bytes() != data:
            raise RuntimeError(f'{name} changed during verification')
    print('False-source and supported-opcode artifact-mutation controls: PASS', flush=True)
    report = {'lean': version, 'proof_declarations': count, 'axioms': axioms, 'review': sizes,
              'sha256': {name: hashlib.sha256(data).hexdigest() for name, data in original.items()}}
    (BUILD / 'report.json').write_text(json.dumps(report, indent=2) + '\n')
    print('ALL CHECKS PASSED', flush=True)


if __name__ == '__main__':
    try:
        main()
    except (RuntimeError, OSError, subprocess.SubprocessError, StopIteration) as error:
        print(f'VERIFICATION FAILED: {error}', file=sys.stderr)
        sys.exit(1)
